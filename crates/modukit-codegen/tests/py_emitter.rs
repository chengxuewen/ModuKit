//! Wave-2 Python volume M1: the generated embed floor's pins (D100 R3-A
//! gates 1-2 + 4). The face is emitted by `emit_embed_py` at the
//! `--embed_header` door (beside the cpp wrapper, per golden.rs:34-37 the
//! `generate()` fdset corpus is NOT the seam) and byte-pinned here - the
//! cpp_emitter.rs pattern, never in golden.rs's explicit list.

use std::path::{Path, PathBuf};

use modukit_codegen::emit_embed_py;

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crate lives under <repo>/crates/")
        .to_path_buf()
}

fn embed_header() -> String {
    let root = repo_root();
    std::fs::read_to_string(root.join("contracts/modukit_embed.h"))
        .expect("checked-in embed header")
}

#[test]
fn embed_python_floor_matches_golden() {
    let produced = emit_embed_py(&embed_header()).expect("python floor emits");
    let golden = repo_root()
        .join("crates/modukit-codegen/testdata/golden")
        .join("modukit_embed.py");
    let golden_text = std::fs::read_to_string(&golden).unwrap_or_else(|e| {
        panic!(
            "golden {} missing (pixi run regen-golden): {e}",
            golden.display()
        )
    });
    assert_eq!(
        produced, golden_text,
        "python floor golden drifted (rerun `pixi run regen-golden` and review the diff)"
    );
}

#[test]
fn emitter_is_deterministic() {
    // Same input, same bytes: no timestamps, no order-dependent output.
    let header = embed_header();
    let first = emit_embed_py(&header).expect("first emit");
    let second = emit_embed_py(&header).expect("second emit");
    assert_eq!(first, second, "python floor emission is not deterministic");
}

#[test]
fn emitted_prototypes_equal_the_rung0_verbs() {
    // Structural pin (cpp_emitter.rs:183 pattern): one PROTOTYPES key per
    // rung-0 header verb, in declaration order, and NO sup verb (M2 tail).
    let header = embed_header();
    let produced = emit_embed_py(&header).unwrap();
    let rung0: Vec<String> = header
        .lines()
        .filter_map(|l| l.strip_prefix("int32_t modukit_"))
        .map(|l| "modukit_".to_string() + l.split('(').next().expect("verb name before ("))
        .filter(|name| !name.starts_with("modukit_sup_"))
        .collect();
    assert_eq!(rung0.len(), 16, "rung-0 verb count moved (16 at M1)");
    for verb in &rung0 {
        assert!(
            produced.contains(&format!("\"{verb}\": (c_int32, ")),
            "python floor lacks the {verb} prototype"
        );
    }
    assert!(
        !produced.contains("\"modukit_sup_"),
        "sup verbs ride the M1 floor - they are the M2 tail (D100 R1)"
    );
    // The banner names the generator (D63: generated floor, never hand-written).
    assert!(
        produced.contains("Generated by modukit-codegen") && produced.contains("DO NOT EDIT"),
        "python floor banner must state generated-by + do-not-edit"
    );
}

#[test]
fn enum_mirrors_carry_header_values() {
    // Every `typedef enum modukit_*` block mirrors value-for-value; the
    // count is pinned at five (the grill-fixed fact base, plan §8).
    let header = embed_header();
    let produced = emit_embed_py(&header).unwrap();
    let mut enums: Vec<(String, Vec<(String, i64)>)> = Vec::new();
    let mut current: Option<(String, Vec<(String, i64)>)> = None;
    for line in header.lines() {
        let t = line.trim();
        if let Some(rest) = t.strip_prefix("typedef enum ")
            && let Some(tag) = rest.strip_suffix(" {")
            && tag.starts_with("modukit_")
        {
            current = Some((tag.to_string(), Vec::new()));
            continue;
        }
        if t.starts_with('}') {
            if let Some(e) = current.take() {
                enums.push(e);
            }
            continue;
        }
        if let Some((_, values)) = current.as_mut()
            && let Some(eq) = t.find("= ")
        {
            let (name, tail) = t.split_at(eq);
            let name = name.trim();
            if name.starts_with("MODUKIT_") {
                let digits: String = tail[2..]
                    .chars()
                    .take_while(|c| c.is_ascii_digit() || *c == '-')
                    .collect();
                if let Ok(n) = digits.parse::<i64>() {
                    values.push((name.to_string(), n));
                }
            }
        }
    }
    assert_eq!(enums.len(), 5, "embed header enum count moved (five at M1)");
    for (tag, values) in &enums {
        let class_name = pascal(tag);
        assert!(
            produced.contains(&format!("class {class_name}:")),
            "python floor lacks the {tag} mirror class"
        );
        for (name, number) in values {
            let short = name.strip_prefix("MODUKIT_").unwrap_or(name);
            assert!(
                produced.contains(&format!("    {short} = {number}")),
                "{class_name} mirror lost value {short} = {number}"
            );
        }
    }
}

#[test]
fn vtable_signage_pins_the_seventeen_members() {
    // Layout mirror of struct modukit_host_embed_v1: 2 guards + 15 slots,
    // in declaration order (SIGNAGE - the guards' struct, not a call path).
    let produced = emit_embed_py(&embed_header()).unwrap();
    let want = [
        "abi_version",
        "size",
        "install",
        "uninstall",
        "resolve",
        "start",
        "stop",
        "state",
        "service_call",
        "bus_publish",
        "bus_subscribe",
        "bus_recv",
        "bus_unsubscribe",
        "clock_now",
        "clock_advance",
        "introspect_snapshot",
        "introspect_events",
    ];
    let mut cursor = 0usize;
    for name in want {
        let entry = format!("(\"{name}\", ");
        let at = produced[cursor..]
            .find(&entry)
            .unwrap_or_else(|| panic!("HostEmbedV1 mirror lacks field {name} in order"));
        cursor += at + entry.len();
    }
    assert_eq!(
        want.len(),
        17,
        "vtable mirror member count (17 = 2 guards + 15 slots)"
    );
}

#[test]
fn emitted_python_compiles() {
    // Smoke (emitted_cpp_passes_fsyntax_only pattern): the floor must parse
    // under the system interpreter; skips cleanly when python3 is absent.
    let produced = emit_embed_py(&embed_header()).unwrap();
    let out_dir =
        std::env::temp_dir().join(format!("modukit-codegen-py-smoke-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&out_dir);
    std::fs::create_dir_all(&out_dir).unwrap();
    let face = out_dir.join("modukit_embed.py");
    std::fs::write(&face, &produced).unwrap();
    let status = std::process::Command::new("python3")
        .args(["-m", "py_compile"])
        .arg(&face)
        .status();
    match status {
        Ok(status) => {
            assert!(status.success(), "emitted python floor failed py_compile");
            let _ = std::fs::remove_dir_all(&out_dir);
        }
        Err(_) => {
            eprintln!("SKIP: python3 not on PATH; py_compile smoke not run");
            let _ = std::fs::remove_dir_all(&out_dir);
        }
    }
}

/// `modukit_kernel_code` -> `KernelCode` (the emitter's own rule, mirrored
/// here so the pin does not trust the code it pins).
fn pascal(tag: &str) -> String {
    let bare = tag.strip_prefix("modukit_").unwrap_or(tag);
    let mut out = String::new();
    let mut upper_next = true;
    for c in bare.chars() {
        if c == '_' {
            upper_next = true;
        } else if upper_next {
            out.extend(c.to_uppercase());
            upper_next = false;
        } else {
            out.push(c);
        }
    }
    out
}
