//! Wave-2 JS volume M1: the generated bridge + facade pins (D102 R3-A gates
//! 1-2 + 4). Both faces are emitted by `emit_embed_js_bridge` /
//! `emit_embed_js_facade` at the `--js_out` door (beside `--py_out`, per
//! golden.rs:34-37 the `generate()` fdset corpus is NOT the seam) and
//! byte-pinned here - the py_emitter.rs pattern, never in golden.rs's list.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use modukit_codegen::{emit_embed_js_bridge, emit_embed_js_facade};

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crate lives under <repo>/crates/")
        .to_path_buf()
}

fn embed_header() -> String {
    let root = repo_root();
    std::fs::read_to_string(root.join("contracts/modukit_embed.h"))
        .expect("checked-in embed header")
}

fn golden(name: &str) -> String {
    let path = repo_root()
        .join("crates/modukit-codegen/testdata/golden")
        .join(name);
    std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "golden {} missing (pixi run regen-golden): {e}",
            path.display()
        )
    })
}

/// The independent rung-0 verb list: header lines starting `int32_t modukit_`,
/// sup rung excluded (the emitter's own M1 filter, re-derived here so the pin
/// does not trust the code it pins).
fn rung0_verbs(header: &str) -> Vec<String> {
    header
        .lines()
        .filter_map(|l| l.strip_prefix("int32_t modukit_"))
        .map(|l| "modukit_".to_string() + l.split('(').next().expect("verb name before ("))
        .filter(|n| !n.starts_with("modukit_sup_"))
        .collect()
}

#[test]
fn bridge_face_matches_golden() {
    let produced = emit_embed_js_bridge(&embed_header()).expect("js bridge emits");
    assert_eq!(
        produced,
        golden("modukit_embed_bridge.rs"),
        "js bridge golden drifted (rerun `pixi run regen-golden` and review the diff)"
    );
}

#[test]
