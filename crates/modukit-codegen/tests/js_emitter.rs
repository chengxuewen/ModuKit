#[test]
fn emitter_is_deterministic() {
    // Same input, same bytes, twice: no timestamps, no order-dependent output.
    let header = embed_header();
    for emit in 0..2 {
        let first = emit_embed_js_bridge(&header).expect("bridge emit");
        let second = emit_embed_js_bridge(&header).expect("bridge emit");
        assert_eq!(
            first, second,
            "bridge emission is not deterministic (run {emit})"
        );
        let f1 = emit_embed_js_facade(&header).expect("facade emit");
        let f2 = emit_embed_js_facade(&header).expect("facade emit");
        assert_eq!(f1, f2, "facade emission is not deterministic (run {emit})");
    }
}

#[test]
fn emitted_bridge_forwarders_equal_rung0_16() {
    let header = embed_header();
    let verbs = rung0_verbs(&header);
    assert_eq!(verbs.len(), 16, "rung-0 verb count moved (16 at M1)");
    let produced = emit_embed_js_bridge(&header).unwrap();
    // Set-equality over the js_name exports: every verb has exactly one
    // forwarder and the bridge exports no other modukit_* function name.
    let want: BTreeSet<String> = verbs.iter().cloned().collect();
    let mut got = BTreeSet::new();
    for line in produced.lines() {
        if let Some(rest) = line.trim().strip_prefix("#[napi(js_name = \"")
            && let Some(name) = rest.split('"').next()
        {
            got.insert(name.to_string());
        }
    }
    assert_eq!(
        got, want,
        "bridge forwarder names must equal the rung-0 verb set"
    );
    // The banner names the generator (D63: generated face, never hand-written).
    assert!(
        produced.contains("Generated by modukit-codegen") && produced.contains("DO NOT EDIT"),
        "bridge banner must state generated-by + do-not-edit"
    );
    // The C door is the only cross-language exit: no modukit-core dependency
    // may appear in the bridge source (it dlopens the .so instead).
    assert!(
        !produced.contains("modukit_core::") && !produced.contains("use modukit_core"),
        "bridge must not reference modukit-core as a Rust dependency (C door only)"
    );
}

#[test]
fn facade_functions_equal_bridge_forwarders() {
    let header = embed_header();
    let bridge = emit_embed_js_bridge(&header).unwrap();
    let facade = emit_embed_js_facade(&header).unwrap();
    let mut bridge_names = BTreeSet::new();
    for line in bridge.lines() {
        if let Some(rest) = line.trim().strip_prefix("#[napi(js_name = \"")
            && let Some(name) = rest.split('"').next()
            && name.starts_with("modukit_")
        {
            bridge_names.insert(name.to_string());
        }
    }
    let mut facade_names = BTreeSet::new();
    for line in facade.lines() {
        let t = line.trim();
        if let Some(rest) = t.strip_prefix("exports.")
            && let Some((name, tail)) = rest.split_once(" = addon.")
            && tail.trim_end_matches(';') == name
            && name.starts_with("modukit_")
        {
            facade_names.insert(name.to_string());
        }
    }
    assert_eq!(
        facade_names, bridge_names,
        "facade re-exports must be 1:1 with the bridge forwarders"
    );
    assert_eq!(facade_names.len(), 16, "facade verb count moved (16 at M1)");
}

#[test]
fn enum_mirrors_carry_header_values() {
    // Every `typedef enum modukit_*` block mirrors value-for-value on BOTH
    // faces; the count is pinned at five (the python volume's fact base).
    let header = embed_header();
    let bridge = emit_embed_js_bridge(&header).unwrap();
    let facade = emit_embed_js_facade(&header).unwrap();
    let mut enums: Vec<(String, Vec<(String, i64)>)> = Vec::new();
    let mut current: Option<(String, Vec<(String, i64)>)> = None;
    for line in header.lines() {
        let t = line.trim();
        if let Some(rest) = t.strip_prefix("typedef enum ")
            && let Some(tag) = rest.strip_suffix(" {")
            && tag.starts_with("modukit_")
        {
            current = Some((tag.to_string(), Vec::new()));
            continue;
        }
        if t.starts_with('}') {
            if let Some(e) = current.take() {
                enums.push(e);
            }
            continue;
        }
        if let Some((_, values)) = current.as_mut()
            && let Some(eq) = t.find("= ")
        {
            let (name, tail) = t.split_at(eq);
            let name = name.trim();
            if name.starts_with("MODUKIT_") {
                let digits: String = tail[2..]
                    .chars()
                    .take_while(|c| c.is_ascii_digit() || *c == '-')
                    .collect();
                if let Ok(n) = digits.parse::<i64>() {
                    values.push((name.to_string(), n));
                }
            }
        }
    }
    assert_eq!(enums.len(), 5, "embed header enum count moved (five at M1)");
    for (tag, values) in &enums {
        for (name, number) in values {
            assert!(
                bridge.contains(&format!("pub const {name}: i32 = {number};")),
                "bridge lost the {tag} value {name} = {number}"
            );
            let short = name.strip_prefix("MODUKIT_").unwrap_or(name);
            assert!(
                facade.contains(&format!("  {short}: {number},")),
                "facade lost the {tag} value {short} = {number}"
            );
        }
    }
    // The sixth mirror: the ABI define, value parsed from the header.
    let abi = header
        .lines()
        .find_map(|l| {
            l.trim()
                .strip_prefix("#define MODUKIT_EMBED_ABI_VERSION")
                .map(|v| {
                    v.trim()
                        .chars()
                        .take_while(|c| c.is_ascii_digit())
                        .collect::<String>()
                })
        })
        .expect("ABI define present");
    assert!(
        bridge.contains(&format!(
            "pub const MODUKIT_EMBED_ABI_VERSION: i32 = {abi};"
        )) && facade.contains(&format!("exports.MODUKIT_EMBED_ABI_VERSION = {abi};")),
        "the ABI-version mirror must equal the header define ({abi})"
    );
}

#[test]
fn emitted_facade_parses_under_node() {
    // Smoke (emitted_python_compiles pattern): the facade must parse under
    // the local node; skips cleanly when node is absent.
    let produced = emit_embed_js_facade(&embed_header()).unwrap();
    let out_dir =
        std::env::temp_dir().join(format!("modukit-codegen-js-smoke-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&out_dir);
    std::fs::create_dir_all(&out_dir).unwrap();
    let face = out_dir.join("modukit_embed.js");
    std::fs::write(&face, &produced).unwrap();
    let status = std::process::Command::new("node")
        .args(["--check"])
        .arg(&face)
        .status();
    match status {
        Ok(status) => {
            assert!(status.success(), "emitted js facade failed node --check");
            let _ = std::fs::remove_dir_all(&out_dir);
        }
        Err(_) => {
            eprintln!("SKIP: node not on PATH; node --check smoke not run");
            let _ = std::fs::remove_dir_all(&out_dir);
        }
    }
}
