//! Python embed-face floor emitter (wave-2 Python volume M1+M2, D100 R2-A).
//!
//! Input: the contract ORIGINAL `contracts/modukit_embed.h`, parsed with the
//! same language-neutral text parsers the C++ face uses
//! ([`crate::embed::parse_enums`] / [`crate::embed::parse_verbs`]). The header
//! stays the single authority (ruling C++-3 doctrine, inherited by D100); a
//! second parser or a hand-maintained python source would be exactly the
//! parallel-surface drift D63 forbids.
//!
//! Output: `modukit_embed.py` - the GENERATED ctypes floor over the full
//! 24-verb face (16 rung-0 verbs + the 8 `modukit_sup_*` verbs, D100 R1):
//! - module-level class mirrors of the header's five C enums (values verbatim,
//!   the `MODUKIT_` prefix drops inside the class scope, like the C++ enum
//!   classes),
//! - `PROTOTYPES`: one `(restype, argtypes)` ctypes prototype per verb (both
//!   rungs), parsed from the declarations; `bind(lib)` applies them mechanically,
//! - the i32 return-channel mirror `EMBED_ERRORS` naming the D51 kernel codes
//!   (the same dictionary the C++ `Status::code()` maps onto),
//! - a `ctypes.Structure` mirror of `struct modukit_host_embed_v1` - SIGNAGE
//!   documenting the handshake-guard layout, not the calling path: python
//!   calls the free functions the way the C++ wrapper does.
//!
//! Floor discipline (D63 boundary): generated code only - no semantics, no
//! sugar beyond names. Determinism: no timestamps, no iteration-order
//! dependence; the golden byte-compares and the regen-diff leg own drift.
//! The output targets system python 3.8+ (stdlib `ctypes` only).

use std::fmt::Write as _;

use crate::embed::{CVerb, enum_class_name, parse_enums, parse_verbs};
use crate::error::CodegenError;

/// Emit the Python embed floor from the embed contract header text.
///
/// # Errors
///
/// [`CodegenError::EmbedHeader`] when the text carries no enum block, no verb
/// declaration, no `modukit_host_embed_v1` struct, or a parameter type the
/// ctypes mapping does not know - contract drift is refused, never emitted
/// as a half-floor.
pub fn emit_embed_py(header_text: &str) -> Result<String, CodegenError> {
    let enums = parse_enums(header_text);
    if enums.is_empty() {
        return Err(CodegenError::EmbedHeader(
            "no `typedef enum modukit_*` block found".to_string(),
        ));
    }
    let verbs: Vec<CVerb> = parse_verbs(header_text);
    if verbs.is_empty() {
        return Err(CodegenError::EmbedHeader(
            "no `int32_t modukit_*(` verb declaration found".to_string(),
        ));
    }
    // Both rungs ride the floor since M2 (D100 R1 two-rung scope); the rung
    // counts are computed from the header, never hardcoded into the banner.
    let rung0 = verbs
        .iter()
        .filter(|v| !v.name.starts_with("modukit_sup_"))
        .count();
    let sup = verbs.len() - rung0;
    let kernel_code = enums
        .iter()
        .find(|e| e.tag == "modukit_kernel_code")
        .ok_or_else(|| CodegenError::EmbedHeader("no `modukit_kernel_code` enum".to_string()))?;
    let (guards, slots) = parse_vtable(header_text)?;

    let mut out = String::new();
    let _ = write!(
        out,
        r#""""Generated by modukit-codegen (wave-2 Python volume M1+M2, D100 R2-A) from
modukit_embed.h. DO NOT EDIT - the contract ORIGINAL is the C header this
floor mirrors; skins are generated FROM it (D63: hand-writing a replacement
of this floor is forbidden).

Regen: cargo run -q -p modukit-codegen --bin protoc-gen-modukit --
  @contracts/org.modukit.runtime.proto.fdset @contracts/com.modukit.demo.proto.fdset
  --embed_header contracts/modukit_embed.h --py_out <dir> --output_dir <dir>

Python EMBED FLOOR ({count} verbs = {rung0} rung-0 (the free ABI probe +
the {slots_count} vtable slots) + {sup} modukit_sup_* exe-rung verbs,
D100 R1): enum mirrors with values verbatim, one ctypes prototype per verb,
the i32 return-channel error
mirror, and a layout-pin mirror of struct modukit_host_embed_v1 (SIGNAGE for
the handshake guards only - the calling path is the free functions bound via
PROTOTYPES/bind, the way the C++ wrapper calls them). Floor discipline: no
semantics, no sugar beyond names; stdlib ctypes only; python 3.8+.
"""
import ctypes
from ctypes import (
    POINTER,
    c_char_p,
    c_int32,
    c_int64,
    c_size_t,
    c_uint32,
    c_uint64,
    c_void_p,
)
"#,
        count = verbs.len(),
        rung0 = rung0,
        sup = sup,
        slots_count = slots.len(),
    );

    for e in &enums {
        let _ = writeln!(
            out,
            "\n\nclass {class_name}:\n    \
             \"\"\"mirror of `{tag}` - values verbatim, MODUKIT_ prefix dropped\"\"\"\n",
            class_name = enum_class_name(&e.tag),
            tag = e.tag,
        );
        for (name, number) in &e.values {
            let short = name.strip_prefix("MODUKIT_").unwrap_or(name);
            let _ = writeln!(out, "    {short} = {number}");
        }
    }

    let _ = write!(
        out,
        "\n\n# i32 return-channel mirror: a verb returns 0 (or a byte count) on success\n\
         # and a NEGATIVE D51 code on kernel-domain failure; compare `-EMBED_ERRORS[name]`.\n\
         # Same dictionary the C++ Status::code() maps onto (ruling C++-3 / D51).\n\
         EMBED_ERRORS = {{\n"
    );
    for (name, number) in &kernel_code.values {
        let short = name.strip_prefix("MODUKIT_").unwrap_or(name);
        let _ = writeln!(out, "    \"{short}\": {number},");
    }
    out.push_str("}\n");

    let _ = write!(
        out,
        "\n\n# One ctypes prototype per verb (both rungs): name -> (restype, argtypes), parsed\n\
         # from the header declarations. bind() applies them to a ctypes-opened library.\n\
         PROTOTYPES = {{\n"
    );
    for v in &verbs {
        let c_decl = declare_c(&v.name, &v.params);
        let mapped = map_params(&v.params)?;
        let argtypes = mapped
            .iter()
            .map(|(ct, _)| ct.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        let _ = write!(
            out,
            "    # {c_decl}\n    \"{name}\": (c_int32, [{argtypes}]),\n",
            name = v.name,
            argtypes = argtypes,
        );
    }
    out.push_str("}\n");

    out.push_str(
        "\n\n\
         def bind(lib):\n    \
         \"\"\"Apply PROTOTYPES to a ctypes-opened kernel library; return it.\n\n       \
         Mechanical only: restype/argtypes set per exported symbol. No call\n       \
         semantics live here (floor discipline) - the ambient kernel initializes\n       \
         itself on the first verb call, exactly like the C++ demo's Kernel.\n    \
         \"\"\"\n    \
         for name, (restype, argtypes) in PROTOTYPES.items():\n        \
         fn = getattr(lib, name)\n        \
         fn.restype = restype\n        \
         fn.argtypes = argtypes\n    \
         return lib\n",
    );

    let _ = write!(
        out,
        "\n\n\
         class HostEmbedV1(ctypes.Structure):\n    \
         \"\"\"Layout pin of `struct modukit_host_embed_v1` - {member_count} members\n        \
         (2 handshake guards + {slots_count} verb slots). SIGNAGE for the guards\n        \
         only, NOT the calling path: python calls the free functions via\n        \
         PROTOTYPES/bind, the way the C++ wrapper calls the implementations.\n    \
         \"\"\"\n\n    \
         _fields_ = [\n",
        member_count = guards.len() + slots.len(),
        slots_count = slots.len(),
    );
    for (name, ty) in &guards {
        let _ = writeln!(out, "        (\"{name}\", {ty}),");
    }
    for (name, params) in &slots {
        let mapped = map_params(params)?;
        let args = if mapped.is_empty() {
            String::new()
        } else {
            format!(
                ", {}",
                mapped
                    .iter()
                    .map(|(ct, _)| ct.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        let _ = writeln!(
            out,
            "        (\"{name}\", ctypes.CFUNCTYPE(c_int32{args})),"
        );
    }
    out.push_str("    ]\n");

    Ok(out)
}

/// One member declaration of the vtable struct: `(abi_version, c_uint32)`-style
/// guards and `int32_t (*name)(params...)` slots, read from the
/// `modukit_host_embed_v1` block. Block comments are stripped first (the
/// guards carry trailing `/* ... */` decoration), then the remainder splits
/// on `;` - one statement per member, wrapped slot declarations joined by
/// construction.
/// vtable mirror shape: handshake guards as `(member, ctypes_expr)` plus
/// verb slots as `(slot name, parameter declarations)` - factored out only
/// because the tuple of nested vecs reads densier than the alias.
type Vtable = (Vec<(String, String)>, Vec<(String, Vec<String>)>);

fn parse_vtable(text: &str) -> Result<Vtable, CodegenError> {
    let open = "typedef struct modukit_host_embed_v1 {";
    let start = text.find(open).ok_or_else(|| {
        CodegenError::EmbedHeader(
            "no `typedef struct modukit_host_embed_v1` block found".to_string(),
        )
    })?;
    let body = &text[start + open.len()..];
    let end = body.find("modukit_host_embed_v1;").ok_or_else(|| {
        CodegenError::EmbedHeader("unterminated `modukit_host_embed_v1` struct".to_string())
    })?;
    let struct_body = &body[..end];
    let block = &struct_body[..struct_body.rfind('}').unwrap_or(struct_body.len())];
    let block = strip_block_comments(block);
    let mut guards: Vec<(String, String)> = Vec::new();
    let mut slots: Vec<(String, Vec<String>)> = Vec::new();
    for stmt in block.split(';') {
        let member = stmt.split_whitespace().collect::<Vec<_>>().join(" ");
        let member = member.trim();
        if member.is_empty() {
            continue;
        }
        if let Some(rest) = member.strip_prefix("int32_t (*")
            && let Some((name, tail)) = rest.split_once(")(")
        {
            let inner = tail.trim().strip_suffix(')').unwrap_or("").trim();
            let params: Vec<String> = if inner.is_empty() || inner == "void" {
                Vec::new()
            } else {
                inner.split(',').map(|p| p.trim().to_string()).collect()
            };
            slots.push((name.to_string(), params));
        } else if let Some(rest) = member.strip_prefix("uint32_t ") {
            guards.push((rest.trim().to_string(), "c_uint32".to_string()));
        } else {
            return Err(CodegenError::EmbedHeader(format!(
                "unrecognized vtable member `{member}`"
            )));
        }
    }
    if slots.is_empty() {
        return Err(CodegenError::EmbedHeader(
            "no `typedef struct modukit_host_embed_v1` verb slots found".to_string(),
        ));
    }
    Ok((guards, slots))
}

/// Remove `/* ... */` runs. The contract header carries no verbatim `/*`
/// outside comment openers, so the first-found scan is complete here.
fn strip_block_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(open) = rest.find("/*") {
        out.push_str(&rest[..open]);
        rest = match rest[open..].find("*/") {
            Some(close) => &rest[open + close + 2..],
            None => "",
        };
    }
    out.push_str(rest);
    out
}

/// Map one C parameter declaration onto its ctypes expression.
///
/// Byte-buffer pointers (`uint8_t *` / `const uint8_t *`) ride `c_void_p`:
/// the C door takes an untyped address, and ctypes then accepts bytes,
/// bytearrays, buffers and casts at the call site.
fn map_param(decl: &str) -> Result<String, CodegenError> {
    let norm = decl.split_whitespace().collect::<Vec<_>>().join(" ");
    // The declaration name is the trailing identifier run; the type keeps
    // everything before it, pointer stars included (`const char *manifest_toml`).
    let name_len = norm
        .chars()
        .rev()
        .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
        .count();
    let ty = norm[..norm.len() - name_len].trim_end();
    let ct = match ty {
        "const char *" | "char *" => "c_char_p",
        "const char **" | "char **" => "POINTER(c_char_p)",
        "const uint8_t *" | "uint8_t *" => "c_void_p",
        "int32_t *" => "POINTER(c_int32)",
        "int64_t *" => "POINTER(c_int64)",
        "uint64_t *" => "POINTER(c_uint64)",
        "size_t *" => "POINTER(c_size_t)",
        "int32_t" => "c_int32",
        "int64_t" => "c_int64",
        "uint64_t" => "c_uint64",
        "uint32_t" => "c_uint32",
        "size_t" => "c_size_t",
        other => {
            return Err(CodegenError::EmbedHeader(format!(
                "parameter type `{other}` has no ctypes mapping"
            )));
        }
    };
    Ok(ct.to_string())
}

/// `(ctypes expr, parameter name)` per declaration; names are kept for the
/// comment line, the mapping itself is positional.
fn map_params(params: &[String]) -> Result<Vec<(String, String)>, CodegenError> {
    params
        .iter()
        .map(|p| {
            let name = p
                .rsplit(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                .next()
                .unwrap_or_default()
                .to_string();
            Ok((map_param(p)?, name))
        })
        .collect()
}

/// The C declaration comment above a prototype line (wrapped source joined
/// with single spaces, like `parse_verbs` already does).
fn declare_c(name: &str, params: &[String]) -> String {
    if params.is_empty() {
        format!("int32_t {name}(void)")
    } else {
        format!("int32_t {name}({})", params.join(", "))
    }
}
