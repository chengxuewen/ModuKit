//! Rust skeleton emitter (modules/04 §1: `dl` local dispatch row, Stage 1).
//!
//! Placement-agnostic message shapes only: the dispatch enum is what `dl`
//! executes without serialization and what `exe` (Stage 2) will serialize
//! over the wire - one shape, no divergence (04 §1 closing rule). Generated
//! output is flat top-level Rust: the consumer places it inside its own
//! module tree. No wire codec lives here.

use std::fmt::Write as _;

use crate::descriptor::{Enum, Field, FieldType, File, Label, Message, RUNTIME_PACKAGE, Service};
use crate::error::CodegenError;

/// Names Rust rejects in field position - a proto field with one of these
/// gets the `r#` raw prefix instead of a rename (contract name stays literal).
const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
    "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "self", "static", "struct", "super", "trait", "true", "try", "type", "unsafe",
    "use", "where", "while",
];

/// Emit the `.rs` skeleton for one contract file. `ledger` is the decoded
/// `org.modukit.runtime` file; required when `file` declares services
/// (their skeletons mirror the D27 error record from it, never hand-copied).
pub fn emit_rust(file: &File, ledger: Option<&File>) -> Result<String, CodegenError> {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by protoc-gen-modukit (M4 v0) from {src}.\n\
         // DO NOT EDIT - the authored original is the .proto and the fdset\n\
         // beside it is the machine ledger (D13). Regen: `pixi run regen-golden`.\n\
         //\n\
         // Proto enum value names are contract literals (D12 rule 3), kept\n\
         // verbatim as Rust variants (per-enum allow below).\n",
        src = file.name
    );

    for e in &file.enums {
        emit_enum(&mut out, e)?;
    }
    for m in &file.messages {
        emit_message(&mut out, file, m)?;
    }
    for s in &file.services {
        emit_service(&mut out, file, s)?;
    }
    if !file.services.is_empty() {
        emit_runtime_mirror(&mut out, ledger.ok_or(CodegenError::RuntimeLedgerMissing)?)?;
    }
    Ok(out)
}

fn emit_enum(out: &mut String, e: &Enum) -> Result<(), CodegenError> {
    let sentinel = e.sentinel()?.name.clone();
    let _ = writeln!(
        out,
        "\n/// proto enum `{name}` - hand-numbered values (D12 rule 1),\n\
         /// unknown wire values map to the sentinel (D12 rule 3).\n\
         /// Names are proto contract literals, kept verbatim.\n\
         #[allow(non_camel_case_types)]\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]\n\
         pub enum {name} {{",
        name = e.name
    );
    for v in &e.values {
        let _ = writeln!(out, "    /// tag {n}.", n = v.number);
        if v.name == sentinel {
            // The sentinel doubles as the Rust Default (prost's trick), so
            // messages holding this enum can derive Default too.
            let _ = writeln!(
                out,
                "    #[default]
    {vname} = {n},",
                vname = v.name,
                n = v.number
            );
        } else {
            let _ = writeln!(out, "    {vname} = {n},", vname = v.name, n = v.number);
        }
    }
    let _ = write!(
        out,
        "}}\n\n\
         impl {name} {{\n\
         \x20   /// Wire value -> variant; never panics on an unknown number.\n\
         \x20   #[must_use]\n\
         \x20   pub fn from_i32(value: i32) -> Self {{\n\
         \x20       match value {{\n",
        name = e.name
    );
    for v in &e.values {
        if v.name != sentinel {
            let _ = writeln!(
                out,
                "            {n} => Self::{vname},",
                n = v.number,
                vname = v.name
            );
        }
    }
    let _ = write!(
        out,
        "            _ => Self::{sentinel},\n\
         \x20       }}\n\
         \x20   }}\n\
         }}\n",
        sentinel = sentinel
    );
    Ok(())
}

fn emit_message(out: &mut String, file: &File, m: &Message) -> Result<(), CodegenError> {
    let _ = writeln!(
        out,
        "\n/// proto message `{name}`: owned values across the boundary\n\
         /// (04 §2 - buffers are Vec<u8>, never borrowed pointers).\n\
         #[derive(Debug, Clone, PartialEq, Default)]\n\
         pub struct {name} {{",
        name = m.name
    );
    for f in &m.fields {
        let ty = rust_type(file, f)?;
        let _ = writeln!(
            out,
            "    /// field `{fname}` = tag {n} (hand-written in {pkg}.{mname}).",
            fname = f.name,
            n = f.number,
            pkg = file.package,
            mname = m.name
        );
        let _ = writeln!(out, "    pub {field}: {ty},", field = rust_field(&f.name));
    }
    let _ = writeln!(out, "}}");
    Ok(())
}

fn rust_field(name: &str) -> String {
    if RUST_KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_string()
    }
}

fn rust_type(file: &File, f: &Field) -> Result<String, CodegenError> {
    let bare = match f.kind {
        FieldType::Double => "f64".to_string(),
        FieldType::Float => "f32".to_string(),
        FieldType::Int64 | FieldType::Sfixed64 | FieldType::Sint64 => "i64".to_string(),
        FieldType::Uint64 | FieldType::Fixed64 => "u64".to_string(),
        FieldType::Int32 | FieldType::Sfixed32 | FieldType::Sint32 => "i32".to_string(),
        FieldType::Uint32 | FieldType::Fixed32 => "u32".to_string(),
        FieldType::Bool => "bool".to_string(),
        FieldType::String => "String".to_string(),
        FieldType::Bytes => "Vec<u8>".to_string(),
        FieldType::Enum | FieldType::Message => qualified_local(file, &f.type_name)?,
        FieldType::Group => return Err(CodegenError::wire("GROUP type leaked past decode")),
    };
    Ok(match f.label {
        Label::Repeated => format!("Vec<{bare}>"),
        Label::Optional if matches!(f.kind, FieldType::Message) => format!("Option<{bare}>"),
        Label::Optional => bare,
    })
}

/// Resolve a type reference. v0 keeps every generated file self-contained:
/// the reference must name a type inside this contract file, or one of the
/// runtime ledger types that the mirror below re-emits by name.
fn qualified_local(file: &File, fq: &str) -> Result<String, CodegenError> {
    let bare = fq.rsplit('.').next().unwrap_or(fq).to_string();
    let package = fq
        .strip_prefix('.')
        .unwrap_or(fq)
        .strip_suffix(&format!(".{bare}"))
        .unwrap_or("");
    if package == file.package || package == RUNTIME_PACKAGE {
        Ok(bare)
    } else {
        Err(CodegenError::UnresolvedType(format!(
            "{fq} (from {}) resolves outside package {} / the runtime ledger",
            file.name, file.package
        )))
    }
}

fn emit_service(out: &mut String, file: &File, s: &Service) -> Result<(), CodegenError> {
    let id_const = if file.services.len() == 1 {
        "SERVICE_ID".to_string()
    } else {
        format!("{}_SERVICE_ID", to_snake(&s.name).to_uppercase())
    };
    let _ = writeln!(
        out,
        "\n/// Canonical service id stamped by `(modukit.service_id)` in {src}\n\
         /// (D9): the const is the typed lookup key; short names never cross\n\
         /// a boundary.\n\
         pub const {id_const}: &str = \"{sid}\";",
        src = file.name,
        sid = s.service_id
    );

    let dispatch = format!("{}Dispatch", s.name);
    let _ = writeln!(
        out,
        "\n/// Dispatch message for `{sid}`: one variant per method with typed\n\
         /// args, placement-agnostic (04 §1) - `dl` executes it in-process\n\
         /// without serialization; `exe` (Stage 2) serializes the SAME enum.\n\
         #[derive(Debug, Clone, PartialEq)]\n\
         pub enum {dispatch} {{",
        sid = s.service_id
    );
    for m in &s.methods {
        let req = qualified_local(file, &m.input_type)?;
        let _ = writeln!(out, "    /// rpc {name} -> {req}", name = m.name);
        let _ = writeln!(out, "    {name}({req}),", name = m.name);
    }
    let _ = write!(
        out,
        "}}\n\n\
         impl {dispatch} {{\n\
         \x20   /// Method name carried by this dispatch value (the envelope's\n\
         \x20   /// method id, 04 §2).\n\
         \x20   #[must_use]\n\
         \x20   pub fn method_name(&self) -> &'static str {{\n\
         \x20       match self {{\n"
    );
    for m in &s.methods {
        let _ = writeln!(
            out,
            "            {dispatch}::{name}(_) => \"{name}\",",
            name = m.name
        );
    }
    let _ = write!(
        out,
        "        }}\n\
         \x20   }}\n\
         }}\n\n\
         /// Author trait - the generated skeleton IS the contract surface\n\
         /// (D13 doctrine 2); the impl is hand-written beside it.\n\
         /// The D27 record is a full struct by design (one shared body,\n\
         /// no boxing at v0) - hence the error-size allow.\n\
         #[allow(clippy::result_large_err)]\n\
         pub trait {name}Author {{\n",
        name = s.name
    );
    for m in &s.methods {
        let req = qualified_local(file, &m.input_type)?;
        let resp = qualified_local(file, &m.output_type)?;
        let _ = writeln!(
            out,
            "    /// Synchronous boundary (D6): return `Result` for short work,\n    \
             ///    a job token for long work; never `async` across the ABI.\n    \
             fn {snake}(&self, request: {req}) -> Result<{resp}, Error>;",
            snake = to_snake(&m.name)
        );
    }
    let _ = writeln!(out, "}}");
    Ok(())
}

/// Mirror the D27 shared error record (and its transitive dependencies) from
/// the runtime ledger into a service skeleton, so the module stays
/// self-contained while the .proto remains the single source.
fn emit_runtime_mirror(out: &mut String, ledger: &File) -> Result<(), CodegenError> {
    let _ = writeln!(
        out,
        "\n// ----------------------------------------------------------------\n\
         // Mirrored from org.modukit.runtime.proto (D27 shared body, one\n\
         // record across both code spaces). Generated - edit the .proto.\n\
         // ----------------------------------------------------------------"
    );
    let mut seen: Vec<String> = Vec::new();
    let mut queue: Vec<String> = vec!["Error".to_string()];
    while let Some(name) = queue.pop() {
        if seen.contains(&name) {
            continue;
        }
        if let Some(m) = ledger.message(&name) {
            emit_message(out, ledger, m)?;
            seen.push(name.clone());
            for f in &m.fields {
                if matches!(f.kind, FieldType::Message | FieldType::Enum) {
                    let bare = f
                        .type_name
                        .rsplit('.')
                        .next()
                        .unwrap_or_default()
                        .to_string();
                    if ledger.message(&bare).is_some()
                        || ledger.enums.iter().any(|e| e.name == bare)
                    {
                        if !seen.contains(&bare) {
                            queue.push(bare);
                        }
                    } else {
                        return Err(CodegenError::UnresolvedType(format!(
                            "org.modukit.runtime.{bare} referenced by {name}"
                        )));
                    }
                }
            }
        } else if let Some(e) = ledger.enums.iter().find(|x| x.name == name) {
            emit_enum(out, e)?;
            seen.push(name);
        } else {
            return Err(CodegenError::UnresolvedType(format!(
                "org.modukit.runtime.{name}"
            )));
        }
    }
    Ok(())
}

/// `EchoOne` -> `echo_one` (proto method names are PascalCase by convention).
pub(crate) fn to_snake(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    for (i, c) in name.char_indices() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}
