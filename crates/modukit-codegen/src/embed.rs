//! C++ embed-face wrapper generator (Stage-4 M1 lane #3, ruling C++-3 face B).
//!
//! Input: the contract ORIGINAL `contracts/modukit_embed.h` (HostEmbedV1),
//! read as text. The header is pinned to the Rust-side mirror
//! (`modukit_core::embed_abi::EMBED_VERBS`) by the parity gate
//! (`scripts/check-embed-parity.sh`), so a simple textual parse of the
//! checked-in declarations is legitimate here — a full C parser would be
//! a second authority over one surface (the D-rationale against
//! parallel-source drift).
//!
//! Output: a header-only `modukit_embed.hpp` with
//! - typed `enum class` mirrors of the header's C enums (values verbatim),
//! - a small `Status` type over the verbs' raw i32 channel — chosen over
//!   exceptions deliberately: this face is an FFI boundary, and unwinding
//!   across kernel calls is exactly what the D6 sync-boundary discipline
//!   refuses (documented in the emitted banner too),
//! - one RAII `Kernel` handle class + one forwarding method per verb.
//!
//! `kernel_new`/`kernel_free` are NOT HostEmbedV1 verbs (there are exactly
//! 16, and the parity gate pins that): the embedding kernel is ambient in
//! the process, so the handle owns only the ABI handshake probe. If a D83
//! tail-add introduces create/destroy verbs, the ctor/dtor grows there.

use std::fmt::Write as _;

use crate::error::CodegenError;

/// One parsed C enum from the header (`typedef enum <tag> { NAME = n, ... }`).
pub(crate) struct CEnum {
    pub(crate) tag: String,
    pub(crate) values: Vec<(String, i64)>,
}

/// One parsed verb declaration (`int32_t modukit_x(...)`): the bare verb
/// name and its parameter list verbatim from the header text.
pub(crate) struct CVerb {
    pub(crate) name: String,
    /// Parameter declarations, top-level comma-split, trimmed. Empty for
    /// a `(void)` verb.
    pub(crate) params: Vec<String>,
}

/// Emit the C++ wrapper header text from the embed contract header text.
///
/// # Errors
///
/// [`CodegenError::EmbedHeader`] when the text carries no `typedef enum
/// modukit_*` block or no `int32_t modukit_*(` verb declaration — a header
/// the parser cannot see through is a contract drift, never a silent
/// half-wrapper.
pub fn emit_embed_hpp(header_text: &str) -> Result<String, CodegenError> {
    let enums = parse_enums(header_text);
    if enums.is_empty() {
        return Err(CodegenError::EmbedHeader(
            "no `typedef enum modukit_*` block found".to_string(),
        ));
    }
    let verbs = parse_verbs(header_text);
    if verbs.is_empty() {
        return Err(CodegenError::EmbedHeader(
            "no `int32_t modukit_*(` verb declaration found".to_string(),
        ));
    }

    let mut out = String::new();
    let _ = write!(
        out,
        "/* Generated by protoc-gen-modukit (M1) from modukit_embed.h.\n\
         \x20  DO NOT EDIT - the contract ORIGINAL is the C header this file\n\
         \x20  includes; wrappers are generated FROM it (ruling C++-3).\n\
         \x20  Regen: cargo run -q -p modukit-codegen --bin protoc-gen-modukit --\n\
         \x20  @contracts/org.modukit.runtime.proto.fdset @contracts/com.modukit.demo.proto.fdset\n\
         \x20  --embed_header contracts/modukit_embed.h --output_dir <dir>\n\n\
         \x20  C++ EMBED FACE (Stage-4 M1, ruling C++-3 face B): a header-only\n\
         \x20  RAII/status wrapper over the {count} HostEmbedV1 verbs.\n\
         \x20  Error model: every verb's raw i32 channel rides `modukit::Status`\n\
         \x20  (ok() is `raw >= 0`; code() maps a negative to the typed D51\n\
         \x20  entry). A small status type is chosen OVER exceptions on purpose:\n\
         \x20  this face is an FFI boundary and unwinding across kernel calls is\n\
         \x20  what the D6 sync-boundary discipline refuses.\n\
         \x20  RAII note: HostEmbedV1 has no kernel_new/kernel_free verbs - the\n\
         \x20  embedding kernel is ambient in the process, so `modukit::Kernel`\n\
         \x20  owns only the ABI handshake probe; a D83 tail-add of create/\n\
         \x20  destroy verbs is where ownership would grow. */\n\
         #ifndef MODUKIT_EMBED_HPP\n\
         #define MODUKIT_EMBED_HPP\n\n\
         #include <cstddef>\n\
         #include <cstdint>\n\n\
         #include \"modukit_embed.h\"\n",
        count = verbs.len()
    );

    out.push_str("\nnamespace modukit {\n");

    for e in &enums {
        let class_name = enum_class_name(&e.tag);
        let _ = write!(
            out,
            "\n/* typed mirror of `{tag}` - values verbatim, the MODUKIT_ name\n\
             \x20  prefix drops inside the enum class scope */\n\
             enum class {class_name} : int32_t {{\n",
            tag = e.tag,
            class_name = class_name
        );
        for (name, number) in &e.values {
            let short = name.strip_prefix("MODUKIT_").unwrap_or(name);
            let _ = writeln!(out, "  {short} = {number},");
        }
        let _ = writeln!(out, "}};");
    }

    out.push_str(
        "\n/* One verb result: the header's raw i32 channel. ok() is the\n\
         \x20  header's success rule (`raw >= 0`: 0, or the byte count the verb\n\
         \x20  wrote); code() maps a negative return to the D51 dictionary. */\n\
         class Status {\n\
         \x20public:\n\
         \x20  explicit Status(int32_t raw) : raw_(raw) {}\n\n\
         \x20  [[nodiscard]] bool ok() const {\n\
         \x20    return raw_ >= 0;\n\
         \x20  }\n\
         \x20  [[nodiscard]] int32_t raw() const {\n\
         \x20    return raw_;\n\
         \x20  }\n\
         \x20  [[nodiscard]] KernelCode code() const {\n\
         \x20    return static_cast<KernelCode>(raw_ < 0 ? -raw_ : 0);\n\
         \x20  }\n\n\
         \x20private:\n\
         \x20  int32_t raw_;\n\
         };\n",
    );

    out.push_str(
        "\n/* The embed face as an object: one forwarding method per header verb,\n\
         \x20  in declaration order (D83 tail-add keeps earlier methods stable).\n\
         \x20  Non-copyable by design: the handle is the process-wide kernel\n\
         \x20  binding, not a value. */\n\
         class Kernel {\n\
         \x20public:\n\
         \x20  /* Handshake probe at construction (04 §3 discipline): check\n\
         \x20     abi_version() before trusting any other verb. */\n\
         \x20  Kernel() : abi_(modukit_embed_abi_version()) {}\n\
         \x20  Kernel(const Kernel &) = delete;\n\
         \x20  Kernel &operator=(const Kernel &) = delete;\n\n\
         \x20  [[nodiscard]] int32_t abi_version() const {\n\
         \x20    return abi_;\n\
         \x20  }\n",
    );

    for v in &verbs {
        let method = v.name.strip_prefix("modukit_").unwrap_or(&v.name);
        let signature = parameter_text(&v.params);
        let args = argument_names(&v.params);
        let _ = write!(
            out,
            "\n  [[nodiscard]] Status {method}({signature}) const {{\n\
             \x20    return Status{{modukit_{method}({args})}};\n\
             \x20  }}\n",
            method = method,
            signature = signature,
            args = args,
        );
    }

    let _ = write!(
        out,
        "\nprivate:\n\
         \x20  int32_t abi_;\n\
         }};\n\
         \n}}  // namespace modukit\n\
         \n#endif /* MODUKIT_EMBED_HPP */\n"
    );
    Ok(out)
}

/// Parse every `typedef enum modukit_*` block: tag + `NAME = number` lines.
pub(crate) fn parse_enums(text: &str) -> Vec<CEnum> {
    let mut enums = Vec::new();
    let mut current: Option<CEnum> = None;
    for line in text.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("typedef enum ")
            && let Some(tag) = rest.strip_suffix(" {")
            && tag.starts_with("modukit_")
        {
            current = Some(CEnum {
                tag: tag.to_string(),
                values: Vec::new(),
            });
            continue;
        }
        if trimmed.starts_with('}') {
            if let Some(e) = current.take() {
                enums.push(e);
            }
            continue;
        }
        if let Some(e) = current.as_mut() {
            // value line: `NAME = number,` possibly trailed by a comment
            if let Some(eq) = trimmed.find("= ") {
                let (name, tail) = trimmed.split_at(eq);
                let name = name.trim();
                if name.starts_with("MODUKIT_") {
                    let number_text = tail[2..]
                        .split(|c: char| !(c.is_ascii_digit() || c == '-'))
                        .next()
                        .unwrap_or_default();
                    if let Ok(number) = number_text.parse::<i64>() {
                        e.values.push((name.to_string(), number));
                    }
                }
            }
        }
    }
    enums
}

/// Parse every `int32_t modukit_*(` verb declaration, joining wrapped lines
/// up to the terminating `;`. Function-pointer struct members use the
/// `int32_t (*name)(...)` shape and never match the `int32_t modukit_`
/// line prefix, so the vtable block is skipped by construction.
pub(crate) fn parse_verbs(text: &str) -> Vec<CVerb> {
    let mut verbs = Vec::new();
    let mut pending: Option<String> = None;
    for line in text.lines() {
        let trimmed = line.trim();
        let mut joined_complete = false;
        if let Some(p) = pending.as_mut() {
            p.push(' ');
            p.push_str(trimmed);
            joined_complete = trimmed.ends_with(';');
        } else if let Some(rest) = trimmed.strip_prefix("int32_t ")
            && rest.starts_with("modukit_")
        {
            if trimmed.ends_with(';') {
                finish_verb(rest, &mut verbs);
            } else {
                pending = Some(trimmed.to_string());
            }
        }
        if joined_complete {
            // take() (not mem::take through the borrow) so the slot resets
            // to None - a dead Some("") would swallow every later verb.
            if let Some(full) = pending.take()
                && let Some(rest) = full.strip_prefix("int32_t ")
                && rest.starts_with("modukit_")
            {
                finish_verb(rest, &mut verbs);
            }
        }
    }
    verbs
}

fn finish_verb(rest: &str, verbs: &mut Vec<CVerb>) {
    let Some(open) = rest.find('(') else {
        return;
    };
    let name = rest[..open].trim().to_string();
    let Some(close) = rest.rfind(')') else {
        return;
    };
    let inner = rest[open + 1..close].trim();
    let params: Vec<String> = if inner.is_empty() || inner == "void" {
        Vec::new()
    } else {
        split_top_level_commas(inner)
    };
    verbs.push(CVerb { name, params });
}

/// Top-level comma split (the verb parameters carry no nested commas).
fn split_top_level_commas(inner: &str) -> Vec<String> {
    inner
        .split(',')
        .map(|p| p.trim().to_string())
        .filter(|p| !p.is_empty())
        .collect()
}

/// The emitted C++ parameter list: declarations verbatim from the header.
fn parameter_text(params: &[String]) -> String {
    params.join(", ")
}

/// The call arguments: the trailing identifier of each parameter.
fn argument_names(params: &[String]) -> String {
    params
        .iter()
        .map(|p| {
            p.rsplit(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                .next()
                .unwrap_or_default()
                .to_string()
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// `modukit_kernel_code` -> `KernelCode`.
pub(crate) fn enum_class_name(tag: &str) -> String {
    let bare = tag.strip_prefix("modukit_").unwrap_or(tag);
    let mut out = String::new();
    let mut upper_next = true;
    for c in bare.chars() {
        if c == '_' {
            upper_next = true;
        } else if upper_next {
            out.extend(c.to_uppercase());
            upper_next = false;
        } else {
            out.push(c);
        }
    }
    out
}
