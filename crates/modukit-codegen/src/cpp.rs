//! C++ plugin-face skeleton emitter (Stage-4 M1 lane #3, ruling C++-3 face A).
//!
//! Sibling of `emit` (Rust skeleton) and `cabi` (C shade): same fdset model,
//! same flat text-emission discipline. Messages ride the stock protoc C++
//! output — `--cpp_out` is consumed AS-IS per C++-1, so this module emits
//! ONLY the include wiring and the dispatch skeleton the author fills, and
//! never redefines a message or an enum.
//!
//! The skeleton mirrors the two generated faces that already exist:
//! - the registration info of the Rust skeleton (`SERVICE_ID` const,
//!   method count) becomes `kServiceId` / `kMethodCount` class members;
//! - the byte door of the C shade (`ctx`-free at this face: method name +
//!   bytes in, bytes out, i32 status) becomes `Dispatch`, which parses the
//!   request into the typed message, calls the author's typed virtual, and
//!   serializes the reply into caller memory.
//!
//! Author failures: typed methods MAY throw; `Dispatch` converts any
//! exception to a negative plugin-side code at the door — the C++
//! equivalent of the Rust trait's `Result` — and unwinding never crosses
//! the byte boundary (D6 sync-boundary discipline).

use std::fmt::Write as _;

use crate::descriptor::{File, Service};
use crate::error::CodegenError;

/// Emit the C++ plugin-face header (`<module>.hpp`) for one contract file.
/// Files without services produce nothing here (same rule as the C shade).
pub fn emit_cpp_header(file: &File) -> Result<String, CodegenError> {
    let guard = file.package.to_uppercase().replace('.', "_");
    let pb_include = pb_header_name(&file.name);
    let mut out = String::new();
    let _ = write!(
        out,
        "/* Generated by protoc-gen-modukit (M1) from {src}.\n\
         \x20  DO NOT EDIT - the authored original is the .proto; the fdset\n\
         \x20  beside it is the machine ledger (D13). Regen: `pixi run regen-golden`.\n\n\
         \x20  C++ PLUGIN FACE (Stage-4 M1, ruling C++-3 face A): the dispatch\n\
         \x20  skeleton the author fills. Message types ride the stock protoc\n\
         \x20  C++ output ({pb} included below) - consumed AS-IS per C++-1;\n\
         \x20  nothing here redefines a message or an enum. */\n\
         #ifndef MODUKIT_{guard}_HPP\n\
         #define MODUKIT_{guard}_HPP\n\n\
         #include <cstddef>\n\
         #include <cstdint>\n\
         #include <cstring>\n\
         #include <exception>\n\
         #include <string>\n\n\
         #include \"google/protobuf/message.h\"\n\n\
         #include \"{pb}\"\n",
        src = file.name,
        pb = pb_include,
        guard = guard
    );

    let ns_open = namespace_open(&file.package);
    let ns_close = namespace_close(&file.package);
    let _ = write!(out, "\n{ns_open}\n");
    for s in &file.services {
        emit_service(&mut out, file, s)?;
    }
    let _ = write!(out, "\n{ns_close}\n");

    let _ = write!(out, "\n#endif /* MODUKIT_{guard}_HPP */\n", guard = guard);
    Ok(out)
}

fn emit_service(out: &mut String, file: &File, s: &Service) -> Result<(), CodegenError> {
    let skeleton = format!("{}Skeleton", s.name);
    let _ = write!(
        out,
        "\n/* {name}: the generated surface IS the contract (D13 doctrine 2);\n\
         \x20  the author subclass implements the typed methods below. */\n\
         class {skeleton} {{\n\
         \x20public:\n\
         \x20  /* canonical service id (D9; stamped `(modukit.service_id)` in\n\
         \x20     {src}) */\n\
         \x20  static constexpr const char *kServiceId = \"{sid}\";\n\
         \x20  static constexpr int kMethodCount = {count};\n\n\
         \x20  virtual ~{skeleton}() = default;\n\n\
         \x20  /* Negative dispatch codes: the plugin-side half of the D27 int\n\
         \x20     channel (the byte door mirrors the C ABI shade call shape). */\n\
         \x20  static constexpr int32_t kBadRequest = -1;    // request bytes failed to parse\n\
         \x20  static constexpr int32_t kUnknownMethod = -2; // no method carries that name\n\
         \x20  static constexpr int32_t kReplyTooLarge = -3; // reply exceeds response_cap\n\
         \x20  static constexpr int32_t kAuthorFailure = -4; // typed method threw\n\n\
         \x20  /* Byte door (04 §1 row 3 shape): parse, run the typed method,\n\
         \x20     serialize the reply into caller memory. Returns the number of\n\
         \x20     response bytes written (>= 0) or one of the codes above. */\n\
         \x20  int32_t Dispatch(const char *method, const uint8_t *request,\n\
         \x20                   size_t request_len, uint8_t *response,\n\
         \x20                   size_t response_cap) {{\n\
         \x20    const std::string name(method ? method : \"\");\n\
         \x20    const std::string input(\n\
         \x20        request ? reinterpret_cast<const char *>(request) : \"\", request_len);\n\
         \x20    try {{\n",
        name = s.name,
        skeleton = skeleton,
        src = file.name,
        sid = s.service_id,
        count = s.methods.len(),
    );
    for m in &s.methods {
        let req = qualified_cpp(&m.input_type)?;
        let resp = qualified_cpp(&m.output_type)?;
        let _ = write!(
            out,
            "      if (name == \"{meth}\") {{\n\
             \x20        {req} typed_in;\n\
             \x20        if (!typed_in.ParseFromString(input)) {{\n\
             \x20          return kBadRequest;\n\
             \x20        }}\n\
             \x20        const {resp} typed_out = {meth}(typed_in);\n\
             \x20        return WriteMessage(typed_out, response, response_cap);\n\
             \x20      }}\n",
            meth = m.name,
            req = req,
            resp = resp,
        );
    }
    let _ = write!(
        out,
        "      return kUnknownMethod;\n\
         \x20    }} catch (const std::exception &) {{\n\
         \x20      /* exceptions stop AT the door - never unwound across the\n\
         \x20         byte boundary (D6 sync-boundary discipline). */\n\
         \x20      return kAuthorFailure;\n\
         \x20    }}\n\
         \x20  }}\n\n\
         \x20protected:\n\
         \x20  /* Synchronous boundary (D6): one typed method per rpc, message in /\n\
         \x20     message out; author-owned failure codes ride the reply, throws\n\
         \x20     are converted to kAuthorFailure by the door above. */\n"
    );
    for m in &s.methods {
        let req = qualified_cpp(&m.input_type)?;
        let resp = qualified_cpp(&m.output_type)?;
        let _ = writeln!(
            out,
            "  virtual {resp} {meth}(const {req} &request) = 0;",
            resp = resp,
            meth = m.name,
            req = req,
        );
    }
    let _ = write!(
        out,
        "\n\
         \x20private:\n\
         \x20  static int32_t WriteMessage(const ::google::protobuf::Message &message,\n\
         \x20                            uint8_t *response, size_t response_cap) {{\n\
         \x20    const std::string bytes = message.SerializeAsString();\n\
         \x20    if (bytes.size() > response_cap) {{\n\
         \x20      return kReplyTooLarge;\n\
         \x20    }}\n\
         \x20    std::memcpy(response, bytes.data(), bytes.size());\n\
         \x20    return static_cast<int32_t>(bytes.size());\n\
         \x20  }}\n\
         }};\n"
    );
    Ok(())
}

/// The proto file name (`com.modukit.demo.proto`) -> the stock protoc C++
/// header it generates (`com.modukit.demo.pb.h`).
fn pb_header_name(proto_name: &str) -> String {
    proto_name
        .strip_suffix(".proto")
        .map(|stem| format!("{stem}.pb.h"))
        .unwrap_or_else(|| format!("{proto_name}.pb.h"))
}

/// `.com.modukit.demo.EchoRequest` -> `::com::modukit::demo::EchoRequest`.
fn qualified_cpp(fq: &str) -> Result<String, CodegenError> {
    let dotted = fq
        .strip_prefix('.')
        .ok_or_else(|| CodegenError::UnresolvedType(format!("{fq}: not fully-qualified")))?;
    Ok(format!("::{}", dotted.replace('.', "::")))
}

fn namespace_open(package: &str) -> String {
    let mut out = String::new();
    for part in package.split('.') {
        let _ = writeln!(out, "namespace {part} {{");
    }
    out
}

fn namespace_close(package: &str) -> String {
    let parts: Vec<&str> = package.split('.').collect();
    let mut out = String::new();
    for part in parts.iter().rev() {
        let _ = writeln!(out, "}}  // namespace {part}");
    }
    out
}
