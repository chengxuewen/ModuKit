//! C ABI shade emitter (modules/04 §1 row 3, Stage 1 = **shape only** -
//! the vtable is "frozen later" per the same row; the export-freeze decision
//! is its own trigger-gated question).
//!
//! One `repr(C)` function table per service plus the matching `.h`. Byte
//! buffers cross, status is `i32`, no Rust types appear in the header. The
//! shape deliberately mirrors `modukit-core::abi` (abi_version + size guard
//! fields first, 04 §3) so a generated service rides the same handshake
//! grammar as the plugin descriptor.

use std::fmt::Write as _;

use crate::descriptor::File;
use crate::emit::to_snake;
use crate::error::CodegenError;

/// Emit the Rust shade (`<module>.abi.rs`).
pub fn emit_cabi_rust(file: &File) -> Result<String, CodegenError> {
    let mut out = String::new();
    let _ = write!(
        out,
        "// Generated by protoc-gen-modukit (M4 v0) from {src}.\n\
         // DO NOT EDIT - regenerate with `pixi run regen-golden`.\n\
         //\n\
         // C ABI vtable SHADE - Stage 1 freezes the shape contract only\n\
         // (modules/04 §1: \"frozen later\"). Function pointers take encoded\n\
         // bytes in / bytes out and return an i32 status (>= 0 bytes written,\n\
         // < 0 plugin-side code, the D27 int channel). No Rust types cross.\n\n\
         use std::ffi::c_void;\n\
         use std::mem::size_of;\n",
        src = file.name
    );
    for s in &file.services {
        let table = format!("{}Vtable", s.name);
        let _ = write!(
            out,
            "\n/// Handshake guard fields lead the table (04 §3: version integer +\n\
             /// struct size are both checked before any call).\n\
             #[repr(C)]\n\
             #[derive(Debug, Clone, Copy)]\n\
             pub struct {table} {{\n\
             \x20   /// ABI generation of this table shape (bump on a breaking edit).\n\
             \x20   pub abi_version: u32,\n\
             \x20   /// The provider's compiled `size_of` of this struct; the\n\
             \x20   /// consumer rejects an undersized table before calling anything.\n\
             \x20   pub size: u32,\n"
        );
        for m in &s.methods {
            let field = to_snake(&m.name);
            let ty = format!("{}{}Fn", s.name, m.name);
            let _ = write!(
                out,
                "    \
                 /// fn(ctx, request bytes, request len, response buffer, response\n    \
                 ///    cap) -> bytes written, or a negative plugin-side code.\n    \
                 pub {field}: Option<{ty}>,\n",
                ty = ty,
                field = field
            );
        }
        let _ = write!(
            out,
            "}}\n\n\
             impl {table} {{\n    \
             /// Current table-shape generation.\n    \
             pub const ABI_VERSION: u32 = 1;\n\n    \
             /// The exact compiled size a conforming provider must report.\n    \
             #[must_use]\n    \
             pub const fn expected_size() -> u32 {{\n        \
             size_of::<{table}>() as u32\n    \
             }}\n\
             }}\n"
        );
        for m in &s.methods {
            let ty = format!("{}{}Fn", s.name, m.name);
            let _ = write!(
                out,
                "\n/// `{method}` call shape (same buffer discipline for every\n\
                 /// method; typed frames arrive with the M5 wire codec).\n\
                pub type {ty} = unsafe extern \"C\" fn(\n\
                \x20   ctx: *mut c_void,\n\
                \x20   request: *const u8,\n\
                \x20   request_len: usize,\n\
                \x20   response: *mut u8,\n\
                \x20   response_cap: usize,\n\
                ) -> i32;\n",
                method = m.name,
                ty = ty
            );
        }
    }
    Ok(out)
}

/// Emit the matching C header (`<module>.h`). No Rust types, stdint only.
pub fn emit_cabi_header(file: &File) -> Result<String, CodegenError> {
    let guard = file.package.to_uppercase().replace('.', "_");
    let mut out = String::new();
    let _ = write!(
        out,
        "/* Generated by protoc-gen-modukit (M4 v0) from {src}.\n\
         \x20 DO NOT EDIT - regenerate with `pixi run regen-golden`.\n\n\
         \x20 C ABI vtable SHADE - Stage 1 freezes the shape contract only\n\
         \x20 (modules/04 §1). Bytes in / bytes out, i32 status: >= 0 is the\n\
         \x20 number of response bytes written, < 0 is a provider-side code\n\
         \x20 (the D27 int channel). No Rust types appear here. */\n\
         #ifndef MODUKIT_{guard}_H\n\
         #define MODUKIT_{guard}_H\n\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\n\
         #ifdef __cplusplus\n\
         extern \"C\" {{\n\
         #endif\n",
        src = file.name,
        guard = guard
    );
    for s in &file.services {
        let snake = to_snake(&s.name);
        let _ = write!(
            out,
            "\n/* canonical service id (D9; stamped `(modukit.service_id)` in\n\
             \x20  {src}) */\n\
             #define MODUKIT_{guard}_{upper}_SERVICE_ID \"{sid}\"\n\n\
             /* {svc}: byte-buffer call shapes, i32 status returns */\n",
            src = file.name,
            guard = guard,
            upper = s.name.to_uppercase(),
            sid = s.service_id,
            svc = s.name
        );
        for m in &s.methods {
            let _ = write!(
                out,
                "typedef int32_t (*{pkg}_{snake}_{meth}_fn)(\n\
                 \x20   void *ctx,\n\
                 \x20   const uint8_t *request, size_t request_len,\n\
                 \x20   uint8_t *response, size_t response_cap);\n",
                pkg = file.package.replace('.', "_"),
                snake = snake,
                meth = to_snake(&m.name)
            );
        }
        let pkg = file.package.replace('.', "_");
        let _ = write!(
            out,
            "typedef struct {pkg}_{snake}_vtable {{\n\
             \x20   /* handshake guards first: version integer + struct size (04 §3) */\n\
             \x20   uint32_t abi_version;\n\
             \x20   uint32_t size; /* sizeof(struct {pkg}_{snake}_vtable) as compiled by the provider */\n"
        );
        for m in &s.methods {
            let _ = writeln!(
                out,
                "    {pkg}_{snake}_{meth}_fn {meth};",
                pkg = file.package.replace('.', "_"),
                snake = snake,
                meth = to_snake(&m.name)
            );
        }
        let _ = writeln!(
            out,
            "}} {pkg}_{snake}_vtable;",
            pkg = file.package.replace('.', "_"),
            snake = snake
        );
    }
    let _ = write!(
        out,
        "\n\
         #ifdef __cplusplus\n\
         }}\n\
         #endif\n\n\
         #endif /* MODUKIT_{guard}_H */\n",
        guard = guard
    );
    Ok(out)
}
