//! C++ plugin-face host wrapper generator (Stage-5 N1, D96 ruling 2/5).
//!
//! Sibling of `embed` (face B over `modukit_embed.h`): this module turns the
//! checked-in contract original `contracts/modukit_plugin.h` into a
//! header-only C++ view over the HOST TABLE a plugin receives at `start`.
//! The same parse-not-reinvent discipline applies - the parity gate pins the
//! header to `abi::HostAbiV2`, so a textual parse of the typedef struct and
//! the slot typedefs is the one authority-preserving way to emit (see the
//! module doc of `embed.rs` for the rationale this copies).
//!
//! The wrapper exposes the v1 `register_service` unconditionally and the
//! parsed v2 slots behind the declared major: the v2 table exists only for a
//! plugin that declared `MODUKIT_ABI_VERSION_V2`, so `has_bus()` is exactly
//! `table->size >= sizeof(modukit_host_abi_v2)`; a slot called without it
//! answers `kNoV2` (the D51 SCHEMA_INVALID number) and never derefs.

use std::fmt::Write as _;

use crate::error::CodegenError;

/// One parsed slot typedef: bare slot name (`bus_publish`), the return type
/// text, and the parameter declarations verbatim (leading `void *user` kept -
/// the forwarder strips it into the table's own `user`).
struct Slot {
    name: String,
    ret: String,
    params: Vec<String>,
}

/// Emit the C++ plugin-face host wrapper text from the plugin contract
/// header text.
///
/// # Errors
///
/// [`CodegenError::EmbedHeader`] when the text carries no
/// `modukit_host_abi_v2` struct or no fn-pointer slots to forward - a
/// header the parser cannot see through is contract drift, never a silent
/// half-wrapper.
pub fn emit_plugin_hpp(header_text: &str) -> Result<String, CodegenError> {
    let slots = parse_slot_typedefs(header_text);
    let fields = parse_struct_fields(header_text, "modukit_host_abi_v2");
    let v3_fields = parse_struct_fields(header_text, "modukit_host_abi_v3");
    let mut forwarded: Vec<&Slot> = Vec::new();
    for (ty, name) in &fields {
        if ty.ends_with("_fn_t") && name != "register_service" {
            let Some(slot) = slots.iter().find(|s| *name == s.name) else {
                return Err(CodegenError::EmbedHeader(format!(
                    "modukit_plugin.h: struct field `{name}` has no `modukit_{name}_fn_t` typedef"
                )));
            };
            forwarded.push(slot);
        }
    }
    if forwarded.is_empty() {
        return Err(CodegenError::EmbedHeader(
            "no mailbox slot typedefs found in modukit_plugin.h".to_string(),
        ));
    }
    // Wave-2 T1 (D99 R2): the v3 table's TAIL slots ride the same parse;
    // the seven prefix fields repeat the v2 list verbatim and stay
    // forwarded off the v2 view (the byte-identical prefix makes that
    // honest - same slot pointers, same trampolines behind them).
    let v2_names: Vec<&str> = fields.iter().map(|(_, n)| n.as_str()).collect();
    let mut forwarded_v3: Vec<&Slot> = Vec::new();
    for (ty, name) in &v3_fields {
        if ty.ends_with("_fn_t") && !v2_names.contains(&name.as_str()) {
            let Some(slot) = slots.iter().find(|s| *name == s.name) else {
                return Err(CodegenError::EmbedHeader(format!(
                    "modukit_plugin.h: struct field `{name}` has no `modukit_{name}_fn_t` typedef"
                )));
            };
            forwarded_v3.push(slot);
        }
    }
    let has_v3 = !forwarded_v3.is_empty();
    // Banner/constructor interpolations (inline `{name}` captures).
    let count = forwarded.len();
    let tail = if has_v3 {
        ", and per parsed HostAbiV3 tail slot"
    } else {
        ""
    };
    let guard = if has_v3 {
        " (`has_timer()` for the v3 tail)"
    } else {
        ""
    };
    let no_v3 = if has_v3 { "kNoV2/kNoV3" } else { "kNoV2" };
    let v3_init = if has_v3 {
        ",\n      v3_(table != nullptr &&\n              table->size >= sizeof(modukit_host_abi_v3)\n                  ? reinterpret_cast<const modukit_host_abi_v3 *>(table)\n                  : nullptr)"
    } else {
        ""
    };

    let mut out = String::new();
    out.push_str("/* Generated by protoc-gen-modukit (N1) from modukit_plugin.h.\n");
    out.push_str("  DO NOT EDIT - the contract ORIGINAL is the C header this file\n");
    out.push_str("  includes; the wrapper is generated FROM it (same discipline as\n");
    out.push_str("  modukit_embed.hpp, ruling C++-3 face B).\n");
    out.push_str("  Regen: cargo run -q -p modukit-codegen --bin protoc-gen-modukit --\n");
    out.push_str(
        "  @contracts/org.modukit.runtime.proto.fdset @contracts/com.modukit.demo.proto.fdset\n",
    );
    out.push_str("  --plugin_header contracts/modukit_plugin.h --output_dir <dir>\n\n");
    let _ = write!(
        out,
        "  C++ PLUGIN FACE host view (Stage-5 N1, D96 ruling 2/5; the wave-2\n  T1 v3 clock-door views per D99 R2): one forwarding method per\n  parsed HostAbiV2 slot ({count} today), the timer tail forwarded\n  behind the HostAbiV3 size guard{tail}. `has_bus()` is the size\n  guard a plugin owes before reading the v2 tail{guard}; a slot\n  called without its table answers {no_v3} and never dereferences.\n",
    );
    out.push_str("  Status is the raw negated-D51 i32 channel. No exceptions across\n");
    out.push_str("  the boundary (D6 sync-boundary discipline, as the embed wrapper). */\n");
    out.push_str("#ifndef MODUKIT_PLUGIN_HPP\n#define MODUKIT_PLUGIN_HPP\n\n");
    out.push_str("#include <cstddef>\n#include <cstdint>\n\n");
    out.push_str("#include \"modukit_plugin.h\"\n\nnamespace modukit {\n\n");
    let _ = write!(
        out,
        "/* View over the host table handed to a plugin's start (borrowed for\n  the call; 01 §3 rule 2 applies unchanged to v2 and v3). */\nclass Host {{\n public:\n  explicit Host(const modukit_host_abi_v1 *table)\n    : v1_(table),\n      v2_(table != nullptr &&\n              table->size >= sizeof(modukit_host_abi_v2)\n                  ? reinterpret_cast<const modukit_host_abi_v2 *>(table)\n                  : nullptr){v3_init}\n  {{\n  }}\n\n",
    );
    out.push_str("  /* The frozen v1 verb works on either table (v2 is the v1 prefix\n     plus the mailbox tail, D96 ruling 2; v3 is the v2 prefix plus the\n     timer tail, D99 R2). */\n  [[nodiscard]] int64_t register_service(\n      const char *service_id, modukit_service_call_fn_t call) const {\n    return v1_ != nullptr\n               ? v1_->register_service(v1_->user, service_id, call)\n               : kNoTable;\n  }\n\n");
    out.push_str("  /* The v2 door: true only when the declared major delivered a\n     table at least sizeof(modukit_host_abi_v2) wide. */\n  [[nodiscard]] bool has_bus() const {\n    return v2_ != nullptr;\n  }\n");
    if has_v3 {
        out.push_str("\n  /* The v3 door: true only when the declared major delivered a\n     table at least sizeof(modukit_host_abi_v3) wide (the timer tail). */\n  [[nodiscard]] bool has_timer() const {\n    return v3_ != nullptr;\n  }\n");
    }
    out.push_str("\n  /* No table at all (null) vs a narrower declared major: the\n     D51 numbers ride the same int channel as the verbs. */\n  static constexpr int32_t kNoTable = -14; /* NOT_FOUND */\n  static constexpr int32_t kNoV2 = -11;   /* SCHEMA_INVALID */\n");
    if has_v3 {
        out.push_str("  static constexpr int32_t kNoV3 = -11;   /* SCHEMA_INVALID */\n");
    }

    for slot in &forwarded {
        let params = slot
            .params
            .iter()
            .skip(1)
            .cloned()
            .collect::<Vec<String>>()
            .join(", ");
        let args = slot
            .params
            .iter()
            .skip(1)
            .map(|p| tail_ident(p))
            .collect::<Vec<String>>()
            .join(", ");
        let _ = write!(
            out,
            "\n  [[nodiscard]] {ret} {name}({params}) const {{\n    return v2_ != nullptr\n               ? v2_->{name}(v2_->user, {args})\n               : kNoV2;\n  }}\n",
            ret = slot.ret,
            name = slot.name,
            params = params,
            args = args,
        );
    }
    for slot in &forwarded_v3 {
        let params = slot
            .params
            .iter()
            .skip(1)
            .cloned()
            .collect::<Vec<String>>()
            .join(", ");
        let args = slot
            .params
            .iter()
            .skip(1)
            .map(|p| tail_ident(p))
            .collect::<Vec<String>>()
            .join(", ");
        let _ = write!(
            out,
            "\n  [[nodiscard]] {ret} {name}({params}) const {{\n    return v3_ != nullptr\n               ? v3_->{name}(v3_->user, {args})\n               : kNoV3;\n  }}\n",
            ret = slot.ret,
            name = slot.name,
            params = params,
            args = args,
        );
    }

    let _ = write!(
        out,
        "\n private:\n  const modukit_host_abi_v1 *v1_;\n  const modukit_host_abi_v2 *v2_;{v3_member}}};\n\n}}  // namespace modukit\n\n#endif /* MODUKIT_PLUGIN_HPP */\n",
        v3_member = if has_v3 {
            "\n  const modukit_host_abi_v3 *v3_;\n"
        } else {
            "\n"
        },
    );
    Ok(out)
}

/// The trailing identifier of a parameter declaration (`size_t value_len`
/// -> `value_len`) - same rule as the embed wrapper's `argument_names`.
fn tail_ident(param: &str) -> String {
    param
        .rsplit(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .next()
        .unwrap_or_default()
        .to_string()
}

/// Join wrapped `typedef ...;` statements onto one line, then keep the
/// fn-pointer slot shapes: `typedef <ret> (*modukit_<name>_fn_t)(<params>);`.
fn parse_slot_typedefs(text: &str) -> Vec<Slot> {
    let mut slots = Vec::new();
    let mut pending = String::new();
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() {
            continue;
        }
        if trimmed.starts_with("typedef ") {
            pending = trimmed.to_string();
        } else if !pending.is_empty() {
            pending.push(' ');
            pending.push_str(trimmed);
        } else {
            continue;
        }
        if pending.ends_with(';') {
            if let Some(slot) = parse_slot_stmt(&pending) {
                slots.push(slot);
            }
            pending.clear();
        }
    }
    slots
}

fn parse_slot_stmt(stmt: &str) -> Option<Slot> {
    let rest = stmt.strip_prefix("typedef ")?.trim_end_matches(';');
    let open = rest.find("(*")?;
    let ret = rest[..open].trim().to_string();
    let after = &rest[open + 2..];
    let name_end = after.find(')')?;
    let ty_name = after[..name_end].trim();
    let bare = ty_name.strip_prefix("modukit_")?.strip_suffix("_fn_t")?;
    let params_start = after[name_end + 1..].find('(')?;
    let inner = after[name_end + 1 + params_start + 1..]
        .trim_end()
        .strip_suffix(')')?
        .trim()
        .to_string();
    let params: Vec<String> = if inner.is_empty() || inner == "void" {
        Vec::new()
    } else {
        inner.split(',').map(|p| p.trim().to_string()).collect()
    };
    Some(Slot {
        name: bare.to_string(),
        ret,
        params,
    })
}

/// The `modukit_host_abi_v2` / `modukit_host_abi_v3` struct's `(type,`
/// name) members, in order (the tag names which table is parsed).
fn parse_struct_fields(text: &str, tag: &str) -> Vec<(String, String)> {
    let mut fields = Vec::new();
    let mut inside = false;
    let open = format!("typedef struct {tag} {{");
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with(&open) {
            inside = true;
            continue;
        }
        if inside {
            if trimmed.starts_with('}') {
                break;
            }
            if trimmed.is_empty()
                || trimmed.starts_with("/*")
                || trimmed.starts_with('*')
                || trimmed.starts_with("///")
            {
                continue;
            }
            let Some(body) = trimmed.strip_suffix(';') else {
                continue;
            };
            let Some(sp) = body.rfind(' ') else { continue };
            let (ty, name) = (body[..sp].trim(), body[sp + 1..].trim());
            if name.is_empty() {
                continue;
            }
            fields.push((ty.to_string(), name.to_string()));
        }
    }
    fields
}
