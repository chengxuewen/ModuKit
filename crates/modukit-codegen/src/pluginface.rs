//! C++ plugin-face host wrapper generator (Stage-5 N1, D96 ruling 2/5).
//!
//! Sibling of `embed` (face B over `modukit_embed.h`): this module turns the
//! checked-in contract original `contracts/modukit_plugin.h` into a
//! header-only C++ view over the HOST TABLE a plugin receives at `start`.
//! The same parse-not-reinvent discipline applies - the parity gate pins the
//! header to `abi::HostAbiV2`, so a textual parse of the typedef struct and
//! the slot typedefs is the one authority-preserving way to emit (see the
//! module doc of `embed.rs` for the rationale this copies).
//!
//! The wrapper exposes the v1 `register_service` unconditionally and the
//! parsed v2 slots behind the declared major: the v2 table exists only for a
//! plugin that declared `MODUKIT_ABI_VERSION_V2`, so `has_bus()` is exactly
//! `table->size >= sizeof(modukit_host_abi_v2)`; a slot called without it
//! answers `kNoV2` (the D51 SCHEMA_INVALID number) and never derefs.

use std::fmt::Write as _;

use crate::error::CodegenError;

/// One parsed slot typedef: bare slot name (`bus_publish`), the return type
/// text, and the parameter declarations verbatim (leading `void *user` kept -
/// the forwarder strips it into the table's own `user`).
struct Slot {
    name: String,
    ret: String,
    params: Vec<String>,
}

/// Emit the C++ plugin-face host wrapper text from the plugin contract
/// header text.
///
/// # Errors
///
/// [`CodegenError::EmbedHeader`] when the text carries no
/// `modukit_host_abi_v2` struct or no fn-pointer slots to forward - a
/// header the parser cannot see through is contract drift, never a silent
/// half-wrapper.
pub fn emit_plugin_hpp(header_text: &str) -> Result<String, CodegenError> {
    let slots = parse_slot_typedefs(header_text);
    let fields = parse_struct_fields(header_text);
    let mut forwarded: Vec<&Slot> = Vec::new();
    for (ty, name) in &fields {
        if ty.ends_with("_fn_t") && name != "register_service" {
            let Some(slot) = slots.iter().find(|s| *name == s.name) else {
                return Err(CodegenError::EmbedHeader(format!(
                    "modukit_plugin.h: struct field `{name}` has no `modukit_{name}_fn_t` typedef"
                )));
            };
            forwarded.push(slot);
        }
    }
    if forwarded.is_empty() {
        return Err(CodegenError::EmbedHeader(
            "no mailbox slot typedefs found in modukit_plugin.h".to_string(),
        ));
    }

    let mut out = String::new();
    let _ = write!(
        out,
        "/* Generated by protoc-gen-modukit (N1) from modukit_plugin.h.\n\
         \x20  DO NOT EDIT - the contract ORIGINAL is the C header this file\n\
         \x20  includes; the wrapper is generated FROM it (same discipline as\n\
         \x20  modukit_embed.hpp, ruling C++-3 face B).\n\
         \x20  Regen: cargo run -q -p modukit-codegen --bin protoc-gen-modukit --\n\
         \x20  @contracts/org.modukit.runtime.proto.fdset @contracts/com.modukit.demo.proto.fdset\n\
         \x20  --plugin_header contracts/modukit_plugin.h --output_dir <dir>\n\n\
         \x20  C++ PLUGIN FACE host view (Stage-5 N1, D96 ruling 2/5): one\n\
         \x20  forwarding method per parsed HostAbiV2 slot ({count} today),\n\
         \x20  behind the declared major - `has_bus()` is the size guard a\n\
         \x20  plugin owes before reading the v2 tail. Status is the raw\n\
         \x20  negated-D51 i32 channel; a slot called without a v2 table\n\
         \x20  answers kNoV2 and never dereferences. No exceptions across the\n\
         \x20  boundary (D6 sync-boundary discipline, as the embed wrapper). */\n\
         #ifndef MODUKIT_PLUGIN_HPP\n\
         #define MODUKIT_PLUGIN_HPP\n\n\
         #include <cstddef>\n\
         #include <cstdint>\n\n\
         #include \"modukit_plugin.h\"\n\n\
         namespace modukit {{\n\n\
         /* View over the host table handed to a plugin's start (borrowed for\n\
         \x20  the call; 01 §3 rule 2 applies unchanged to v2). */\n\
         class Host {{\n\
         \x20public:\n\
         \x20  explicit Host(const modukit_host_abi_v1 *table)\n\
         \x20      : v1_(table),\n\
         \x20        v2_(table != nullptr &&\n\
         \x20                table->size >= sizeof(modukit_host_abi_v2)\n\
         \x20                    ? reinterpret_cast<const modukit_host_abi_v2 *>(table)\n\
         \x20                    : nullptr)\n\
         \x20  {{\n\
         \x20  }}\n\n\
         \x20  /* The frozen v1 verb works on either table (v2 is the v1\n\
         \x20     prefix plus the mailbox tail, D96 ruling 2). */\n\
         \x20  [[nodiscard]] int64_t register_service(\n\
         \x20      const char *service_id, modukit_service_call_fn_t call) const {{\n\
         \x20    return v1_ != nullptr\n\
         \x20               ? v1_->register_service(v1_->user, service_id, call)\n\
         \x20               : kNoTable;\n\
         \x20  }}\n\n\
         \x20  /* The v2 door: true only when the declared major delivered a\n\
         \x20     table at least sizeof(modukit_host_abi_v2) wide. */\n\
         \x20  [[nodiscard]] bool has_bus() const {{\n\
         \x20    return v2_ != nullptr;\n\
         \x20  }}\n\n\
         \x20  /* No table at all (null) vs declared-major-1 (no v2 tail): the\n\
         \x20     D51 numbers ride the same int channel as the verbs. */\n\
         \x20  static constexpr int32_t kNoTable = -14; /* NOT_FOUND */\n\
         \x20  static constexpr int32_t kNoV2 = -11;   /* SCHEMA_INVALID */\n",
        count = forwarded.len()
    );

    for slot in &forwarded {
        let params = slot
            .params
            .iter()
            .skip(1)
            .cloned()
            .collect::<Vec<String>>()
            .join(", ");
        let args = slot
            .params
            .iter()
            .skip(1)
            .map(|p| tail_ident(p))
            .collect::<Vec<String>>()
            .join(", ");
        let _ = write!(
            out,
            "\n  [[nodiscard]] {ret} {name}({params}) const {{\n\
             \x20    return v2_ != nullptr\n\
             \x20               ? v2_->{name}(v2_->user, {args})\n\
             \x20               : kNoV2;\n\
             \x20  }}\n",
            ret = slot.ret,
            name = slot.name,
            params = params,
            args = args,
        );
    }

    let _ = write!(
        out,
        "\n\x20private:\n\
         \x20  const modukit_host_abi_v1 *v1_;\n\
         \x20  const modukit_host_abi_v2 *v2_;\n\
         }};\n\n\
         }}  // namespace modukit\n\n\
         #endif /* MODUKIT_PLUGIN_HPP */\n"
    );
    Ok(out)
}

/// The trailing identifier of a parameter declaration (`size_t value_len`
/// -> `value_len`) - same rule as the embed wrapper's `argument_names`.
fn tail_ident(param: &str) -> String {
    param
        .rsplit(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .next()
        .unwrap_or_default()
        .to_string()
}

/// Join wrapped `typedef ...;` statements onto one line, then keep the
/// fn-pointer slot shapes: `typedef <ret> (*modukit_<name>_fn_t)(<params>);`.
fn parse_slot_typedefs(text: &str) -> Vec<Slot> {
    let mut slots = Vec::new();
    let mut pending = String::new();
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() {
            continue;
        }
        if trimmed.starts_with("typedef ") {
            pending = trimmed.to_string();
        } else if !pending.is_empty() {
            pending.push(' ');
            pending.push_str(trimmed);
        } else {
            continue;
        }
        if pending.ends_with(';') {
            if let Some(slot) = parse_slot_stmt(&pending) {
                slots.push(slot);
            }
            pending.clear();
        }
    }
    slots
}

fn parse_slot_stmt(stmt: &str) -> Option<Slot> {
    let rest = stmt.strip_prefix("typedef ")?.trim_end_matches(';');
    let open = rest.find("(*")?;
    let ret = rest[..open].trim().to_string();
    let after = &rest[open + 2..];
    let name_end = after.find(')')?;
    let ty_name = after[..name_end].trim();
    let bare = ty_name.strip_prefix("modukit_")?.strip_suffix("_fn_t")?;
    let params_start = after[name_end + 1..].find('(')?;
    let inner = after[name_end + 1 + params_start + 1..]
        .trim_end()
        .strip_suffix(')')?
        .trim()
        .to_string();
    let params: Vec<String> = if inner.is_empty() || inner == "void" {
        Vec::new()
    } else {
        inner.split(',').map(|p| p.trim().to_string()).collect()
    };
    Some(Slot {
        name: bare.to_string(),
        ret,
        params,
    })
}

/// The `modukit_host_abi_v2` struct's `(type, name)` members, in order.
fn parse_struct_fields(text: &str) -> Vec<(String, String)> {
    let mut fields = Vec::new();
    let mut inside = false;
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("typedef struct modukit_host_abi_v2 {") {
            inside = true;
            continue;
        }
        if inside {
            if trimmed.starts_with('}') {
                break;
            }
            if trimmed.is_empty()
                || trimmed.starts_with("/*")
                || trimmed.starts_with('*')
                || trimmed.starts_with("///")
            {
                continue;
            }
            let Some(body) = trimmed.strip_suffix(';') else {
                continue;
            };
            let Some(sp) = body.rfind(' ') else { continue };
            let (ty, name) = (body[..sp].trim(), body[sp + 1..].trim());
            if name.is_empty() {
                continue;
            }
            fields.push((ty.to_string(), name.to_string()));
        }
    }
    fields
}
