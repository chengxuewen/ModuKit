#!/usr/bin/env python3
"""examples/py/host_demo.py - the wave-2 Python embed demo (D100 volume M1;
mirror of examples/cpp/host_demo.cc scenes [1]-[11], one-for-one, same scene
labels and success-string shape). Proof that the HostEmbedV1 face is not
paper for Python either: the application calls ONLY the generated ctypes
floor (bindings/py/modukit_embed.py, regenerated by scripts/demo-wave2-py.sh
from contracts/modukit_embed.h) over the ambient Rust process-global kernel
in libmodukit_core.so (the M0 cdylib). Fixture leg: the same real C++ plugin
.so the cpp M1 demo drives (argv[2]).

Word list, one line per verb, in one honest chain (16 rung-0 verbs over 11
scenes - some scenes merge verbs, exactly like the cpp demo):
    embed_abi_version -> install -> resolve -> start -> state
    -> service_call (EchoRequest/EchoReply over the demo contract)
    -> bus_publish -> bus_subscribe -> bus_recv -> bus_unsubscribe
    -> clock_now -> clock_advance (Real domain: pinned REFUSAL, not a
       silent no-op - the header's rule, asserted as an expected code)
    -> introspect_snapshot -> introspect_events (the opaque-bytes codecs
       documented in embed.rs/ embed_codec.rs are parsed field by field)
    -> stop -> uninstall.
Prints `PY-DEMO PASS` only when every step asserted clean; exit 77 = skip
when the kernel .so / fixture .so / regenerated skin is absent;
DEMO_PY_SABOTAGE=1 corrupts the manifest at exactly ONE named point
(scene [2]) so the gate must RED.

Payload codec note (plan §3 M1 step-0, measured RED on this box 2026-10-22):
the pinned protoc is libprotoc 36.2 but system protobuf-python is 3.6.1 and
refuses the generated module (`No module named runtime_version` class), so
this demo carries the pre-drawn hand-rolled minimal fixture codec below
(precedent: the cpp demo's own hand-parsed codecs at host_demo.cc:184-218).
Payload bytes are pinned to examples/cpp/host_demo.cc:39 kPayload. The
generated floor itself is untouched by this branch - it carries no protobuf
dependency at all.
"""

import ctypes
import os
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "bindings" / "py"))
import modukit_embed as skin  # noqa: E402  (generated floor; import after path)

K_PLUGIN_ID = "com.example.cpp.demo"
K_SERVICE_ID = b"com.modukit.demo.DemoService"
K_TOPIC = "com.example.cpp.demo.status"
K_PAYLOAD = b"embed-demo-payload"  # pinned to host_demo.cc:39 kPayload
K_BUS_VALUE = b"alpha-signal"

failures = 0


def check(ok, what):
    global failures
    if not ok:
        print("FAIL: %s" % what)
        failures += 1
    else:
        print("ok:   %s" % what)


def put_varint(value):
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        if value:
            out.append(byte | 0x80)
        else:
            out.append(byte)
            return bytes(out)


def read_varint(buf, off):
    value = 0
    shift = 0
    while True:
        byte = buf[off]
        off += 1
        value |= (byte & 0x7F) << shift
        if not byte & 0x80:
            return value, off
        shift += 7


def encode_echo_request(payload):
    """EchoRequest{ bytes payload = 1 } (com.modukit.demo.proto): tag
    field 1, wire type 2, then the length-delimited bytes."""
    return b"\x0a" + put_varint(len(payload)) + payload


def decode_echo_reply(buf):
    """EchoReply{ bytes payload = 1; DemoStatus status = 2 } -> (payload,
    status). Unknown fields are walked and skipped (proto2 wire discipline,
    the decoder dogfoods D12 rule 2 like the codegen's own reader)."""
    payload = b""
    status = None
    off = 0
    while off < len(buf):
        key, off = read_varint(buf, off)
        field, wire = key >> 3, key & 7
        if wire == 2:
            length, off = read_varint(buf, off)
            value = buf[off : off + length]
            off += length
            if field == 1:
                payload = value
        elif wire == 0:
            value, off = read_varint(buf, off)
            if field == 2:
                status = value
        else:
            return payload, status  # shape this fixture never emits
    return payload, status


def manifest_for(so_path):
    """scene [2] build point: the deploy-tier manifest TOML for the fixture."""
    if os.getenv("DEMO_PY_SABOTAGE") is not None:
        # THE single sabotage point (documented in scripts/demo-wave2-py.sh):
        # an unknown placement must be refused at the install door.
        print("[sabotage] DEMO_PY_SABOTAGE=1 -> corrupting manifest")
        return (
            'id = "%s"\nversion = "0.1.0"\n[entry]\nkind = "dlx"\nartifact = "%s"\n'
            % (K_PLUGIN_ID, so_path)
        )
    return (
        'id = "%s"\nversion = "0.1.0"\n[entry]\nkind = "dl"\nartifact = "%s"\n'
        % (K_PLUGIN_ID, so_path)
    )


def main():
    if len(sys.argv) < 3:
        print("SKIP: usage: host_demo.py <libmodukit_core.so> <path-to-libcpp-example-plugin.so>")
        return 77
    core_so, fixture_so = sys.argv[1], sys.argv[2]
    for missing in (core_so, fixture_so):
        if not os.path.exists(missing):
            print("SKIP: file missing at %s" % missing)
            return 77

    print("=== ModuKit wave-2 M1 Python embed demo ===")
    try:
        lib = skin.bind(ctypes.CDLL(core_so))
    except OSError as exc:
        print("SKIP: kernel .so not loadable (%s)" % exc)
        return 77

    # [1] embed_abi_version: the floor's own handshake probe.
    check(
        lib.modukit_embed_abi_version() == 1,  # MODUKIT_EMBED_ABI_VERSION, embed.h:28
        "[1] embed_abi_version == 1",
    )

    # [2] install: manifest-v0 TOML in, kernel-owned canonical id out.
    toml = manifest_for(fixture_so)
    plugin_id = ctypes.c_char_p()
    rc = lib.modukit_install(toml.encode(), ctypes.byref(plugin_id))
    check(
        rc == 0
        and plugin_id.value is not None
        and plugin_id.value == K_PLUGIN_ID.encode(),
        "[2] install -> canonical id (kernel-owned bytes)",
    )
    if failures != 0:
        print("PY-DEMO FAIL (%d, install door)" % failures)
        return 1  # nothing downstream is reachable without a plugin
    pid = plugin_id.value

    # [3] resolve + [4] start + [5] state: the dl handshake and the walk.
    check(lib.modukit_resolve(pid) == 0, "[3] resolve -> ABI v1 handshake green")
    check(lib.modukit_start(pid) == 0, "[4] start -> ACTIVE")
    state = ctypes.c_int32(-1)
    check(
        lib.modukit_state(pid, ctypes.byref(state)) == 0
        and state.value == skin.PluginState.STATE_ACTIVE,
        "[5] state == ACTIVE (4)",
    )

    # [6] service_call: typed round trip over the frozen message shape.
    req_bytes = encode_echo_request(K_PAYLOAD)
    resp = ctypes.create_string_buffer(len(req_bytes) + 256)
    rc = lib.modukit_service_call(
        K_SERVICE_ID, b"echo", req_bytes, len(req_bytes), resp, len(resp)
    )
    echo_ok = False
    if rc >= 0:
        payload, status = decode_echo_reply(resp.raw[:rc])
        echo_ok = payload == K_PAYLOAD and status == 1  # DEMO_STATUS_OK
    check(echo_ok, "[6] service_call Echo round-trips the payload (status OK)")
    rc_bad = lib.modukit_service_call(
        b"com.example.nope", b"echo", req_bytes, len(req_bytes), resp, len(resp)
    )
    check(
        rc_bad == -skin.EMBED_ERRORS["NOT_FOUND"],
        "[6] service_call unknown id -> NOT_FOUND(-14)",
    )

    # [7] bus: publish, late-join subscribe, recv (cap discipline honored).
    check(
        lib.modukit_bus_publish(
            K_TOPIC.encode(), skin.Qos.QOS_LATEST_VALUE, K_BUS_VALUE, len(K_BUS_VALUE)
        )
        == 0,
        "[7] bus_publish latest-value",
    )
    queue_id = ctypes.c_int32(-1)
    rc = lib.modukit_bus_subscribe(K_TOPIC.encode(), ctypes.byref(queue_id))
    check(rc == queue_id.value and queue_id.value >= 1,
          "[7] bus_subscribe -> kernel-owned queue id")
    got_len = ctypes.c_size_t(0)
    small = ctypes.create_string_buffer(4)
    rc = lib.modukit_bus_recv(queue_id.value, small, 4, ctypes.byref(got_len))
    check(
        rc == -skin.EMBED_ERRORS["QUOTA_EXCEEDED"] and got_len.value == len(K_BUS_VALUE),
        "[7] bus_recv too-small cap -> QUOTA_EXCEEDED, need reported",
    )
    out = ctypes.create_string_buffer(len(K_BUS_VALUE) + 16)
    rc = lib.modukit_bus_recv(queue_id.value, out, len(out), ctypes.byref(got_len))
    check(
        rc >= 0 and got_len.value == len(K_BUS_VALUE) and out.raw[:got_len.value] == K_BUS_VALUE,
        "[7] bus_recv (late join) gets the exact value back",
    )
    check(
        lib.modukit_bus_unsubscribe(queue_id.value) == 0
        and lib.modukit_bus_recv(queue_id.value, out, len(out), ctypes.byref(got_len))
        == -skin.EMBED_ERRORS["NOT_FOUND"],
        "[7] bus_unsubscribe retires the queue id",
    )

    # [8] clock: the ambient kernel runs the Real domain (embed.rs decision
    # 1), so now() answers and the dial REFUSES - pinned code, documented.
    now_ns = ctypes.c_int64(-1)
    check(
        lib.modukit_clock_now(ctypes.byref(now_ns)) == 0 and now_ns.value >= 0,
        "[8] clock_now >= 0 ns",
    )
    check(
        lib.modukit_clock_advance(1000000) == -skin.EMBED_ERRORS["CLOCK_DIAL_REFUSED"],
        "[8] clock_advance on Real -> CLOCK_DIAL_REFUSED (never a no-op)",
    )

    # [9] introspect_snapshot: size query then exact copy; the documented
    # line codec parses and carries this plugin's ACTIVE row.
    snap_len = ctypes.c_size_t(0)
    rc = lib.modukit_introspect_snapshot(None, 0, ctypes.byref(snap_len))
    check(rc == snap_len.value and snap_len.value > 0,
          "[9] introspect_snapshot size query (NULL buffer)")
    snap = ctypes.create_string_buffer(snap_len.value)
    copied = ctypes.c_size_t(0)
    rc = lib.modukit_introspect_snapshot(snap, snap_len.value, ctypes.byref(copied))
    snap_ok = False
    if rc >= 0 and copied.value == snap_len.value:
        text = snap.raw[:copied.value].decode("utf-8", "replace")
        snap_ok = (
            "plugin\t%s\tACTIVE" % K_PLUGIN_ID in text
            and "service\torg.modukit.snapshot\t" in text
            and "counters\t" in text
        )
    check(snap_ok, "[9] introspect_snapshot: documented line codec parses")

    # [10] introspect_events: resumable LE record walk; the lifecycle
    # transitions of THIS plugin must be on the ring.
    ev_len = ctypes.c_size_t(0)
    cursor = ctypes.c_uint64(0)
    rc = lib.modukit_introspect_events(0, None, 0, ctypes.byref(ev_len), ctypes.byref(cursor))
    check(rc >= 0 and ev_len.value > 28, "[10] introspect_events size query")
    events = ctypes.create_string_buffer(ev_len.value)
    ev_copied = ctypes.c_size_t(0)
    rc = lib.modukit_introspect_events(
        0, events, ev_len.value, ctypes.byref(ev_copied), ctypes.byref(cursor)
    )
    saw_lifecycle = False
    tiled = False
    if rc >= 0:
        off = 0
        last_seq = 0
        while off + 28 <= ev_copied.value:
            kind, seq, _ts_ns, plen = struct.unpack_from("<iQQQ", events.raw, off)
            if (
                kind == skin.EventKind.EVENT_LIFECYCLE
                and events.raw[off + 28 : off + 28 + len(K_PLUGIN_ID)] == K_PLUGIN_ID.encode()
            ):
                saw_lifecycle = True
            last_seq = seq
            off += 28 + plen
        tiled = off == ev_copied.value and cursor.value == last_seq
    check(saw_lifecycle and tiled,
          "[10] introspect_events: LE records tile the buffer; lifecycle rows found")

    # [11] stop + uninstall close the walk (and the plugin's services).
    check(lib.modukit_stop(pid) == 0, "[11] stop -> RESOLVED")
    check(
        lib.modukit_state(pid, ctypes.byref(state)) == 0
        and state.value == skin.PluginState.STATE_RESOLVED,
        "[11] state == RESOLVED (6)",
    )
    check(lib.modukit_uninstall(pid) == 0, "[11] uninstall -> UNINSTALLED")
    check(
        lib.modukit_state(pid, ctypes.byref(state)) == 0
        and state.value == skin.PluginState.STATE_UNINSTALLED,
        "[11] state == UNINSTALLED (0)",
    )
    check(
        lib.modukit_resolve(pid) == -skin.EMBED_ERRORS["CONTRACT_VIOLATION"],
        "[11] resolve from UNINSTALLED -> CONTRACT_VIOLATION (table guard)",
    )

    if failures != 0:
        print("PY-DEMO FAIL (%d)" % failures)
        return 1
    print("PY-DEMO PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
