#!/usr/bin/env bash
# leg: plugin-wire v1 goldens + ledger parity (wave-2 plugin door batch 1,
# D106 plan T1.3). Three arms, one exit code:
#  (a) goldens: re-run the wire-golden bin into a temp dir; every checked-in
#      byte under contracts/golden/wire-v1 must match the regeneration
#      (diff names the drifted file; the census is pinned at exactly 14
#      .frame + index.txt on both sides so same-name extras cannot hide);
#  (b) ledger: every "NAME = value" constant line in contracts/
#      modukit_wire.h must have its `pub const NAME` twin in crates/
#      modukit-core/src/proc_wire.rs with the same value (Rust right-hand
#      expressions like 64 * 1024 are evaluated), and every pub const of
#      proc_wire.rs must have a ledger line - missing on either side is RED;
#  (c) --self-test: scratch-copy, flip one golden byte (plant 1) and
#      separately bump one ledger number (plant 2); both MUST go red (C0).
# The script never touches repo files; the check.sh block skips this leg
# cleanly when the batch-1 shelf or pixi (cargo owner, D65) is absent.
set -uo pipefail
SELF=$(realpath "$0") # absolute for the self-test re-exec below
cd "$(dirname "$0")/.."
IN="${MODUKIT_GATE_INPUT_DIR:-}"; [ -n "$IN" ] && IN="${IN%/}/"

# ---- self-test ----
if [ "${1:-}" = "--self-test" ]; then
  fail=0
  s=$(mktemp -d)
  trap 'rm -rf "$s"' EXIT
  mkdir -p "$s/contracts" "$s/crates/modukit-core/src"
  cp contracts/modukit_wire.h "$s/contracts/"
  cp crates/modukit-core/src/proc_wire.rs "$s/crates/modukit-core/src/"
  cp -r contracts/golden "$s/contracts/"
  # plant 1: golden drift - flip the second ACK payload byte (header is 6).
  printf 'A' | dd of="$s/contracts/golden/wire-v1/ACK.frame" bs=1 seek=7 count=1 conv=notrunc status=none
  if MODUKIT_GATE_INPUT_DIR="$s" bash "$SELF" > /dev/null 2>&1; then
    echo "self-test FAIL (check-wire-parity.sh): planted golden drift NOT caught"
    fail=1
  fi
  # plant 2: ledger lie - restore goldens, bump one constant value.
  rm -rf "$s/contracts/golden"
  sed -i 's/^\( \* MSG_DUE = \)9$/\190/' "$s/contracts/modukit_wire.h"
  grep -q 'MSG_DUE = 90' "$s/contracts/modukit_wire.h" || { echo "self-test FAIL: plant did not land"; fail=1; }
  cp -r contracts/golden "$s/contracts/"
  if MODUKIT_GATE_INPUT_DIR="$s" bash "$SELF" > /dev/null 2>&1; then
    echo "self-test FAIL (check-wire-parity.sh): planted ledger lie NOT caught"
    fail=1
  fi
  if [ "$fail" -eq 0 ]; then
    echo "self-test OK (check-wire-parity.sh): both planted defects caught"
  fi
  exit "$fail"
fi

HEADER="${IN}contracts/modukit_wire.h"
GOLD="${IN}contracts/golden/wire-v1"
PW="${IN}crates/modukit-core/src/proc_wire.rs"
for f in "$HEADER" "$PW"; do
  if [ ! -f "$f" ]; then
    echo "check-wire-parity: RED (missing $f)"
    exit 1
  fi
done
if [ ! -d "$GOLD" ]; then
  echo "check-wire-parity: RED (missing goldens dir $GOLD)"
  exit 1
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# ---- (a) regeneration byte-diff ----
export PATH="$HOME/.pixi/bin:$PATH"
if command -v pixi >/dev/null 2>&1; then CARGO=(pixi run cargo); else CARGO=(cargo); fi
if ! "${CARGO[@]}" run -q -p modukit-codegen --bin wire-golden -- --out "$tmp/gen" > "$tmp/gen.log" 2>&1; then
  echo "check-wire-parity: RED (wire-golden regeneration failed; last log lines:)"
  tail -n 5 "$tmp/gen.log"
  exit 1
fi
gen_n=$(ls "$tmp/gen"/*.frame 2>/dev/null | wc -l)
gold_n=$(ls "$GOLD"/*.frame 2>/dev/null | wc -l)
if [ "$gen_n" -ne 14 ] || [ "$gold_n" -ne 14 ] || [ ! -f "$GOLD/index.txt" ]; then
  echo "check-wire-parity: RED (frame census gen=$gen_n checked-in=$gold_n index=$([ -f "$GOLD/index.txt" ] && echo y || echo n), expect 14 + index.txt)"
  exit 1
fi
if ! diff -r "$tmp/gen" "$GOLD" > "$tmp/drift.log" 2>&1; then
  echo "check-wire-parity: RED (goldens drift - regenerated bytes differ, files named:)"
  sed 's/^/  /' "$tmp/drift.log"
  exit 1
fi

# ---- (b) ledger <-> proc_wire constant cross-check (both directions) ----
grep -oE '^ \* [A-Z0-9_]+ = -?[0-9]+' "$HEADER" | sed 's/^ \* //; s/ = / /' | sort > "$tmp/ledger.txt"
grep -oE '^pub const [A-Z0-9_]+:' "$PW" | sed 's/^pub const //; s/:$//' | sort > "$tmp/rust.txt"
if [ ! -s "$tmp/ledger.txt" ] || [ ! -s "$tmp/rust.txt" ]; then
  echo "check-wire-parity: RED (constant extraction empty - table grammar drift?)"
  exit 1
fi
bad=0
while IFS=' ' read -r name lval; do
  rval=$(awk -v n="$name" '$0 ~ "^pub const " n ":" { sub(/^[^=]*=[ \t]*/, ""); sub(/;.*/, ""); print }' "$PW")
  if [ -z "$rval" ]; then
    echo "check-wire-parity: RED (ledger constant has no pub const: $name)"
    bad=1
    continue
  fi
  if [ "$lval" != "$rval" ] && ! awk "BEGIN{exit !(($lval) == ($rval))}" 2>/dev/null; then
    echo "check-wire-parity: RED (value mismatch: $name ledger=$lval rust=$rval)"
    bad=1
  fi
done < "$tmp/ledger.txt"
while IFS= read -r name; do
  grep -q "^$name " "$tmp/ledger.txt" || {
    echo "check-wire-parity: RED (pub const has no ledger line: $name)"
    bad=1
  }
done < "$tmp/rust.txt"
if [ "$bad" -ne 0 ]; then
  exit 1
fi

echo "check-wire-parity: ok ($gen_n goldens byte-identical to regeneration; $(wc -l < "$tmp/ledger.txt") ledger constants match proc_wire.rs)"
